class McpProtocolVersionError extends Error {}

/**
 * Read a whole non-streaming body, bounded.
 *
 * The bound is a local ceiling, not a statement about the peer: a body this client refused
 * to buffer may well have been a perfectly good answer to a command the authority already
 * applied. Callers must not translate it into "the request never arrived".
 */
async function readWholeBody(response) {
  const announced = Number(response.headers.get('content-length') ?? 0)
  if (announced > MCP_RESPONSE_MAX_BYTES) {
    await response.body?.cancel()
    throw new McpResponseLimitError(`MCP response exceeded the ${MCP_RESPONSE_MAX_BYTES}-byte local limit`)
  }
  if (response.body === null) return ''
  const reader = response.body.getReader()
  const chunks = []
  let total = 0
  for (;;) {
    const { done, value } = await reader.read()
    if (done) break
    total += value.byteLength
    if (total > MCP_RESPONSE_MAX_BYTES) {
      await reader.cancel()
      throw new McpResponseLimitError(`MCP response exceeded the ${MCP_RESPONSE_MAX_BYTES}-byte local limit`)
    }
    chunks.push(Buffer.from(value))
  }
  return Buffer.concat(chunks).toString('utf8')
}

/** JSON-RPC ids are compared by type as well as value: `1` and `"1"` are different ids. */
const sameRpcId = (a, b) => typeof a === typeof b && a === b

/** A well-formed JSON-RPC response to *this* request, or undefined. */
function rpcResponseFor(value, id) {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) return undefined
  if (value.jsonrpc !== '2.0') return undefined
  if (value.result === undefined && value.error === undefined) return undefined
  return sameRpcId(value.id, id) ? value : undefined
}

/**
 * Read a Streamable HTTP SSE body until the response to *this* request arrives.
 *
 * Three things this has to get right, and the earlier version got none of them:
 *
 *   · **Framing.** An SSE event ends at a blank line and its data is the concatenation of
 *     every `data:` line in it, joined by newlines. Treating one line as one message
 *     mis-parses any pretty-printed or chunk-split payload.
 *   · **Correlation.** The stream legitimately carries server-initiated requests and
 *     notifications before the response — the Streamable HTTP transport explicitly permits
 *     it. Taking the first frame that happens to have a `result` accepts an answer to
 *     someone else's question.
 *   · **Termination.** Closing the stream after the response is a SHOULD, not a MUST, so
 *     waiting for EOF hands a conforming-but-chatty server the power to hang this client
 *     until the deadline. Finish on the matched event and cancel the rest.
 *   · **Resumability.** Every event may carry an `id:`, and that id is the cursor a
 *     `Last-Event-ID` GET resumes from. It is recorded as each event passes, including the
 *     events this request is not waiting for, because the cursor is per stream and not per
 *     request. A client that read only `data:` lines had no cursor at all and could only
 *     answer a broken stream by re-deciding, which is the one thing it must not do.
 */
async function readSseResponse(response, id, session) {
  if (response.body === null) return undefined
  const reader = response.body.getReader()
  const decoder = new TextDecoder()
  let buffered = ''
  let total = 0
  try {
    for (;;) {
      const { done, value } = await reader.read()
      if (done) break
      total += value.byteLength
      if (total > MCP_RESPONSE_MAX_BYTES) {
        throw new McpResponseLimitError(`MCP response exceeded the ${MCP_RESPONSE_MAX_BYTES}-byte local limit`)
      }
      buffered += decoder.decode(value, { stream: true })
      let boundary
      // An event is terminated by a blank line; \r\n, \n and \r are all legal separators.
      while ((boundary = /\r\n\r\n|\n\n|\r\r/.exec(buffered)) !== null) {
        const frame = buffered.slice(0, boundary.index)
        buffered = buffered.slice(boundary.index + boundary[0].length)
        const matched = sseFrameResponse(frame, id, session)
        if (matched !== undefined) return matched
      }
    }
    // A stream that ended without a blank line still carries a final event.
    return sseFrameResponse(buffered, id, session)
  } finally {
    await reader.cancel().catch(() => {})
  }
}

/** One SSE event: its `id:` is the resumption cursor, its `data:` lines join by newline. */
function sseFrameResponse(frame, id, session) {
  const lines = frame.split(/\r\n|\n|\r/)
  const eventId = lines.filter((line) => line.startsWith('id:')).map((line) => line.slice(3).replace(/^ /, '')).pop()
  // The cursor advances on every event, answered or not: it locates a place in the stream,
  // not an answer to this request.
  if (session !== undefined && typeof eventId === 'string' && eventId !== '') session.lastEventId = eventId
  const data = lines
    .filter((line) => line.startsWith('data:'))
    .map((line) => line.slice(5).replace(/^ /, ''))
    .join('\n')
  if (data.trim() === '') return undefined
  let value
  try { value = JSON.parse(data) } catch { return undefined }
  // A batch is legal on the wire; the answer to this request may be any member of it.
  const candidates = Array.isArray(value) ? value : [value]
  for (const candidate of candidates) {
    const matched = rpcResponseFor(candidate, id)
    if (matched !== undefined) return matched
  }
  return undefined
}

const RESUME_ATTEMPTS = envNumber('RULITH_SSE_RESUME_ATTEMPTS', 2, { min: 0, max: 10 })
const RESUME_BACKOFF_MS = envNumber('RULITH_SSE_RESUME_BACKOFF_MS', 250, { min: 10, max: 60_000 })

/**
 * Resume a broken response stream and take the original answer off it.
 *
 * This is the difference between "the connection dropped" and "the outcome is unknown".
 * The base protocol says a client may reopen the stream with `Last-Event-ID` and the
 * server replays what came after that cursor; the answer to the original request is on it,
 * unchanged. No new tool call is made — that is the entire point. Re-deciding here would
 * turn one logical command into two, and for `ApplyAction` that is one extra effect in the
 * outside world.
 *
 * What it must never do is manufacture an ending. A server that cannot replay (no cursor,
 * 405 because it serves no GET stream, an expired session) leaves the outcome unknown, and
 * unknown is returned as unknown so the recovery path can ask the authority. An empty
 * stream read as "nothing happened" is the failure this guards against.
 */
async function resumeSseResponse(id, budgetMs) {
  const session = connection
  if (session?.id === undefined || session.lastEventId === undefined) return undefined
  // The resume lives inside the original call's deadline rather than beside it. Giving each
  // attempt its own window let one 45s call take 75s of wall clock, which is a client
  // quietly deciding how long the operator's configured limit really is.
  if (budgetMs <= 0) return undefined
  const controller = new AbortController()
  const timeout = setTimeout(() => controller.abort(), budgetMs)
  timeout.unref?.()
  try {
    const response = await fetch(MCP_URL, {
      method: 'GET',
      headers: {
        accept: 'text/event-stream',
        authorization: `Bearer ${TOKEN}`,
        'mcp-protocol-version': MCP_PROTOCOL_VERSION,
        'mcp-session-id': session.id,
        'last-event-id': session.lastEventId,
      },
      signal: controller.signal,
    })
    if (response.status === 409) throw await connectionReplacement(response, 'GET (stream resume)')
    if (response.status === 404) {
      await response.body?.cancel()
      throw new McpSessionExpiredError('The MCP session was gone when this client tried to resume its response stream.')
    }
    // 405 is a conforming server that simply does not offer a GET stream; anything else
    // non-2xx is a server that will not replay now. Neither is an answer.
    if (!response.ok || !/text\/event-stream/i.test(String(response.headers.get('content-type') ?? ''))) {
      await response.body?.cancel()
      return undefined
    }
    return await readSseResponse(response, id, session)
  } catch (error) {
    if (error instanceof McpConnectionReplacedError || error instanceof McpSessionExpiredError) throw error
    if (error instanceof McpResponseLimitError) throw error
    return undefined
  } finally {
    clearTimeout(timeout)
  }
}

/**
 * Read a 409 as the one signal it is, or refuse to read it as that signal at all.
 *
 * The reason string is load-bearing: `connection_replaced` means another authenticated
 * client took over and this host must stop reconnecting, while some other 409 is an
 * ordinary conflict this code has no licence to reinterpret. Guessing here would make
 * every future 409 stop the host permanently.
 */
async function connectionReplacement(response, method) {
  let parsed
  try { parsed = JSON.parse(await readWholeBody(response)) } catch { parsed = undefined }
  const error = parsed?.error
  const reason = String(error?.data?.reason ?? '')
  if (error?.code === -32000 && reason === 'connection_replaced') {
    return new McpConnectionReplacedError(String(error.message ?? '').trim()
      || 'This Agent connection was replaced by a newer authenticated client.')
  }
  return new Error(`MCP ${method} failed (HTTP 409)${reason === '' ? '' : `, reason ${JSON.stringify(reason)}`}:`
    + ` ${String(error?.message ?? 'conflict').slice(0, 240)}`)
}

/**
 * **One** authenticated MCP connection, for the whole Agent.
 *
 * Not one per conversation. The Agent has a single effective client, and a second
 * authenticated connection *takes over* from the first — so a process that opened one
 * session per local conversation was not serving two conversations, it was two clients
 * fighting over one Agent, each replacing the other. Focus, the recovery record and the
 * serial gate all belong to the Agent, and there is one of each.
 *
 * Nothing is restored into it. The session id comes from the `Mcp-Session-Id` response
 * header and from nowhere else — not from a stored record, not from a body field a client
 * could put there — because an identity a client can assert is an identity a client can
 * assume.
 */
const connection = {
  id: undefined,
  ready: false,
  opening: undefined,
  /** The last SSE event id seen on this connection's streams; the resumption cursor. */
  lastEventId: undefined,
  /** Set once the authority says this connection was replaced. Terminal, never cleared. */
  replaced: false,
  /** The recovery state the authority last published for this Agent. */
  recovery: undefined,
}

/**
 * The Agent's Board-facing state, held once.
 *
 * A local conversation owns its transcript, its queue and its display name. It does not
 * own focus, the last Board View, or the unresolved call: those are the Agent's, they are
 * what the one authenticated connection carries, and duplicating them per conversation was
 * how two transcripts came to believe in two different Boards.
 */
const board = {
  /** Core-derived {caseId, root, status} focus pairs for this Agent. */
  roots: [],
  /** The Board View the last Board tool result carried. */
  lastView: undefined,
  /** The one submission whose outcome this host does not know. At most one, ever. */
  unresolved: undefined,
  /** The identity of the in-flight handoff claim, which is never the model's. */
  claim: undefined,
  lastRootObservation: new Map(),
  lastFocusPublished: '[]',
  workerGapReported: false,
}

/**
 * One JSON-RPC exchange over Streamable HTTP.
 *
 * `handshake: true` marks the two calls that may be answered under a session id this
 * client has not seen before. Every other call is bound to the session it presented: a
 * peer that answers a queued write under a *different* session has not refreshed metadata,
 * it has answered as somebody else — and the write's outcome is then unknown, not fine.
 *
 * Three server answers are told apart here rather than merged into "the hop failed",
 * because the correct next move differs in each and two of them are not faults at all:
 *
 *   · **409 + `connection_replaced`** — another authenticated client is now this Agent's
 *     one effective client. Terminal for this connection; no reconnect.
 *   · **404** — the transport session is gone. Re-initialize, and learn from the *new*
 *     session's recovery state what became of anything in flight.
 *   · **a broken stream** — resumable from `Last-Event-ID`, and resumed here before
 *     anything is called unknown.
 */
async function mcpRpc(method, params = {}, { timeoutMs = 45_000, id, notification = false, handshake = false } = {}) {
  const session = connection
  const rpcId = notification ? undefined : (id ?? `runtime_${++mcpSeq}`)
  let response
  let raw
  let body
  if (session?.replaced === true) {
    throw new McpConnectionReplacedError('This Agent connection was replaced by a newer authenticated client;'
      + ` ${method} was not sent. Reconnecting automatically would take control back from that client.`)
  }
  const deadlineAt = Date.now() + timeoutMs
  const controller = new AbortController()
  const timeout = setTimeout(() => controller.abort(), timeoutMs)
  timeout.unref?.()
  const presented = session?.id
  try {
    response = await fetch(MCP_URL, {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        accept: 'application/json, text/event-stream',
        connection: 'close',
        authorization: `Bearer ${TOKEN}`,
        'mcp-protocol-version': MCP_PROTOCOL_VERSION,
        ...(presented === undefined ? {} : { 'mcp-session-id': presented }),
      },
      body: JSON.stringify(notification
        ? { jsonrpc: '2.0', method, params }
        : { jsonrpc: '2.0', id: rpcId, method, params }),
      signal: controller.signal,
    })
    // Connection control and session lifetime are decided on the status line, before any
    // body is interpreted as an answer.
    if (response.status === 409) {
      const replacement = await connectionReplacement(response, method)
      if (replacement instanceof McpConnectionReplacedError && session !== undefined) session.replaced = true
      throw replacement
    }
    if (response.status === 404 && presented !== undefined) {
      await response.body?.cancel()
      throw new McpSessionExpiredError(`The MCP session ${presented} no longer exists (HTTP 404) when sending ${method}.`)
    }
    // Keep the same deadline over the response body. `fetch` resolves as soon as headers
    // arrive; clearing here left a peer free to send 200 and hold the body open forever.
    const contentType = String(response.headers.get('content-type') ?? '')
    try {
      if (notification || response.status === 401 || !/text\/event-stream/i.test(contentType)) {
        raw = await readWholeBody(response)
        if (!notification && response.status !== 401) {
          let parsed
          try { parsed = JSON.parse(raw) } catch { parsed = undefined }
          body = rpcResponseFor(parsed, rpcId)
          if (body === undefined && parsed !== undefined) {
            throw new McpCorrelationError(`MCP ${method} was answered with ${describeRpcMismatch(parsed, rpcId)}.`)
          }
        }
      } else {
        // A stream that ends cleanly without the answer and a stream that is cut mid-event
        // are the same situation from here: the answer has not arrived and the request has
        // not been re-issued. Both are resumable, and both must be, because the alternative
        // to resuming is deciding again.
        let broke
        try {
          body = await readSseResponse(response, rpcId, session)
        } catch (error) {
          if (error instanceof McpResponseLimitError) throw error
          broke = error
        }
        for (let attempt = 0; body === undefined && attempt < RESUME_ATTEMPTS; attempt++) {
          // Reopening from the cursor replays the original answer; it does not re-issue the
          // request, and nothing else may be sent until this is settled one way or the other.
          // Between attempts it backs off, and it never outlives this call's own deadline.
          // Not `unref`'d: this wait is part of an unfinished call. An unreferenced timer
          // would let the process decide it had nothing left to do and exit mid-recovery.
          if (attempt > 0) await new Promise((wake) => { setTimeout(wake, RESUME_BACKOFF_MS * attempt) })
          body = await resumeSseResponse(rpcId, deadlineAt - Date.now())
        }
        if (body === undefined) {
          throw new McpCorrelationError(`MCP ${method} received an event stream that never carried a response to request id ${JSON.stringify(rpcId)}`
            + `${broke === undefined ? '' : ` (${String(broke?.cause?.code ?? broke?.message ?? broke).slice(0, 80)})`}`
            + `${session?.lastEventId === undefined ? ' and offered no event id to resume from' : ', and resuming from the last event id did not recover it'}.`)
        }
      }
    } catch (error) {
      // Status is already authoritative. Preserve the credential-specific 401 teaching
      // even if its optional body is truncated or fails while being read.
      if (response.status === 401) raw = ''
      else throw error
    }
  } catch (error) {
    if (error instanceof McpResponseLimitError || error instanceof McpCorrelationError) throw error
    if (error instanceof McpConnectionReplacedError || error instanceof McpSessionExpiredError) throw error
    throw new Error(`Cannot reach the public MCP endpoint ${MCP_URL}: ${error?.cause?.code ?? error?.message ?? error}`)
  } finally {
    clearTimeout(timeout)
  }
  if (response.status === 401) {
    let teaching
    try { teaching = JSON.parse(raw) } catch { teaching = undefined }
    throw new AgentCredentialRejectedError(`Agent MCP token rejected (401): ${teaching?.teaching ?? 'rotate the Agent token in Console and update this client configuration.'}`)
  }
  // The session header is adopted only from an answer this client could read and correlate.
  // A header attached to an unreadable, mismatched or failed response says nothing about
  // which session the command ran under, and adopting it would let the next write present a
  // session identity nobody established.
  const returnedSession = response.headers.get('mcp-session-id')
  if (session !== undefined && typeof returnedSession === 'string' && returnedSession !== ''
    && (notification || body !== undefined)) {
    if (presented !== undefined && presented !== returnedSession) {
      if (!handshake) {
        // Not an innocent metadata refresh. This request was sent under one authenticated
        // session and answered under another, so what happened to it — a write in
        // particular — is not known. Re-establishing the session is the operator's move.
        throw new McpCorrelationError(`MCP ${method} was sent under session ${presented} and answered under ${returnedSession}.`
          + ' The outcome of this command is unknown; the runtime will not adopt the new session identity for it.')
      }
      // A handshake may legitimately be answered under a new session: the old one expired,
      // or this is a fresh initialize. The cursor belongs to the stream that is gone, and
      // presenting it against a different session would be resuming somebody else's place.
      session.lastEventId = undefined
    }
    session.id = returnedSession
  }
  if (notification) {
    if (!response.ok) throw new Error(`MCP ${method} failed (HTTP ${response.status}).`)
    return undefined
  }
  if (!response.ok || body === undefined || body.error !== undefined) {
    const teaching = body?.error?.message ?? String(raw ?? '').replace(/\s+/g, ' ').trim().slice(0, 240)
    throw new Error(`MCP ${method} failed (HTTP ${response.status}): ${teaching || 'empty response'}`)
  }
  return body.result
}

/**
 * Give the session back when this client is finished with it.
 *
 * The base protocol lets a client `DELETE` the session it holds, and doing so is how a
 * Gateway learns that the Agent's one effective client has gone rather than that it has
 * merely fallen silent. Best effort by design: a failure here changes nothing this process
 * still needs, and a client that hung on its own shutdown would be worse than one that
 * left a session to expire.
 */
async function endSession() {
  if (connection.id === undefined || connection.replaced) return
  const ending = connection.id
  connection.id = undefined
  connection.ready = false
  const controller = new AbortController()
  const timeout = setTimeout(() => controller.abort(), 2000)
  timeout.unref?.()
  try {
    await fetch(MCP_URL, {
      method: 'DELETE',
      headers: {
        authorization: `Bearer ${TOKEN}`,
        'mcp-protocol-version': MCP_PROTOCOL_VERSION,
        'mcp-session-id': ending,
      },
      signal: controller.signal,
    })
  } catch { /* the session will expire on its own */ } finally { clearTimeout(timeout) }
}

/** Say precisely how the peer's answer failed to be the answer to this request. */
function describeRpcMismatch(value, id) {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) return 'a body that is not a JSON-RPC response object'
  if (value.jsonrpc !== '2.0') return `jsonrpc=${JSON.stringify(value.jsonrpc)} rather than "2.0"`
  if (value.result === undefined && value.error === undefined) return 'a body carrying neither result nor error'
  return `id ${JSON.stringify(value.id)} rather than the requested ${JSON.stringify(id)}`
}

/** The host-only metadata block of a result. It is never model content. */
const hostMetaOf = (result) => {
  const meta = result?._meta?.[RULITH_META]
  return meta !== null && typeof meta === 'object' && !Array.isArray(meta) ? meta : undefined
}

/**
 * Bring one session up: initialize, acknowledge, and record the authenticated identity
 * the authority attached to its own reply.
 *
 * The Agent identity arrives here, in host metadata, and nowhere else. It is not decoded
 * out of the bearer secret — a client that reads its own token has authenticated nothing
 * — and it is not discovered by opening a Case or reading the Board. An ordinary
 * conversation, including "hello", must reach the model without the Board being touched.
 *
 * Two things are settled before any business can run. The negotiated protocol version has
 * to be the one this client speaks: a host that lists tools happily and then mishandles
 * sessions, resumption or the serial gate is worse than one that refuses, because its
 * failures surface as lost work rather than as an error. And the initialize reply already
 * carries the recovery state, so a fresh process learns that a previous connection left a
 * call in the air without asking a single business question.
 */
async function openSession() {
  const session = connection
  if (session.ready) return session
  session.opening ??= (async () => {
    const result = await mcpRpc('initialize', {
      protocolVersion: MCP_PROTOCOL_VERSION,
      // The declaration is a capability, not a request for one: it says this host obeys
      // the serial-call and recovery discipline the Gateway is entitled to require.
      capabilities: { experimental: { [RULITH_META]: HOST_CAPABILITIES } },
      clientInfo: { name: 'rulith-agent', version: '0.7.0' },
    }, { handshake: true })
    const negotiated = String(result?.protocolVersion ?? '')
    if (negotiated !== MCP_PROTOCOL_VERSION) {
      throw new McpProtocolVersionError(`The MCP endpoint negotiated protocol version ${JSON.stringify(negotiated || '(none)')},`
        + ` and this Runtime speaks ${MCP_PROTOCOL_VERSION}.`
        + '\n  The session, streaming and resumption rules this client depends on are defined by that version, so it stops here'
        + ' rather than listing tools and discovering the difference during a write. Upgrade the endpoint, or use a Runtime'
        + ' built for the version it speaks.')
    }
    const meta = hostMetaOf(result)
    if (typeof meta?.agentId === 'string' && meta.agentId.trim() !== '') agentId ||= meta.agentId.trim()
    absorbHostMeta(meta)
    await mcpRpc('notifications/initialized', {}, { notification: true, timeoutMs: 15_000, handshake: true })
    session.ready = true
    return session
  })()
  try { return await session.opening } catch (error) { session.opening = undefined; throw error }
}

// ── Public MCP tool surface ─────────────────────────────────────────────────
//
// `tools/list` is the whole discovery step. This runtime is an ordinary MCP client of the
// same tools every third-party client sees, and nothing is invented — a tool the authority
// does not advertise cannot be reached from this process at all, and a tool the contract
// does not name cannot be advertised.
//
// Membership itself is not decided here: it is the generated projection above, read from
// the verified contract bundle. What this section owns is what to *do* with it.
const MODEL_TOOLS = RULITH_MCP_SURFACE.map((entry) => entry.name)
/** Tools whose result is a Board View. The artifact read is not one of them. */
const BOARD_TOOLS = new Set(RULITH_MCP_SURFACE.filter((entry) => entry.target === 'core').map((entry) => entry.name))
/**
 * Fields the model never sends, in two families.
 *
 * The first is retired wire: `case: {id, expectedRevision}`, the loose revision fields, the
 * shared-epoch pin and `viewToken`. They used to bind a command to one Case, one write
 * revision or one observation, and their meanings are gone — the authority judges each
 * command against the premises, grounding and policy in force when it executes. They are
 * stripped from every advertised schema *and* refused when a model emits one anyway: old
 * unsupported wire has to fail visibly rather than execute under a guessed contract.
 *
 * The second is envelope metadata that never was a model argument — the Core command kind,
 * the protected query context (`audienceProfile` / `requestedRoots`, which the Gateway
 * injects from the authenticated principal and this host never supplies), the admission
 * block, and the request identity. A model that could name `audienceProfile` could ask to
 * be read as an operator.
 */
const RETIRED_TOOL_FIELDS = ['case', 'expectedRevision', 'caseRevision', 'expectedBoardSharedEpoch', 'viewToken']
const HOST_METADATA_FIELDS = ['kind', 'queryContext', 'audienceProfile', 'requestedRoots', 'admission',
  'interaction', 'requestId', 'boardId', 'protocol']
const HOST_OWNED_TOOL_FIELDS = [...RETIRED_TOOL_FIELDS, ...HOST_METADATA_FIELDS]
/** Retired surfaces. Advertising one is a server that has not been cut over, not a spare tool. */
const RETIRED_TOOL_NAMES = ['agent_protocol', 'GetCompletion', 'GetBoardManifest', 'RunDischarge', 'GetProjection', 'GetChanges']

/**
 * Project the advertised schema onto what the model may say — at the envelope boundary
 * only, which is the boundary these names actually live on.
 *
 * The earlier version deleted any property called `case`, `sessionId` or `requestId` *at
 * any depth*. That was a scope error with teeth in both directions: a Core schema whose
 * `ApplyAction` arguments legitimately carry a business `sessionId` had that argument
 * removed before the model ever saw it, so the model could not send a field Core then
 * required; and a model that nested the same name one level down was not refused, so the
 * deep strip bought no protection either. Host metadata is an *envelope* concept. A
 * property of a business object that happens to share a name with one is business data.
 *
 * Nothing is silently rewritten here. If the server's own schema makes a host-owned name a
 * *required* top-level argument, the two contracts genuinely disagree and startup refuses,
 * rather than trimming the server's requirement and letting Core reject the calls this
 * client induced.
 */
function projectToolSchema(name, schema) {
  if (schema === null || typeof schema !== 'object' || Array.isArray(schema)) {
    return { schema: { type: 'object', properties: {} }, conflict: undefined }
  }
  // A schema may state its shape in composition branches rather than in one property map —
  // the contract's own `OpenCase` is a `oneOf` of a create form and a focus form. Envelope
  // metadata inside a branch is the same contract violation as at the top level, and this
  // client cannot rewrite a branch without changing which forms validate, so it refuses
  // rather than editing.
  for (const key of ['oneOf', 'anyOf', 'allOf']) {
    for (const branch of Array.isArray(schema[key]) ? schema[key] : []) {
      const inBranch = branch !== null && typeof branch === 'object' && !Array.isArray(branch.properties ?? undefined)
        ? Object.keys(branch.properties ?? {}).filter((property) => HOST_OWNED_TOOL_FIELDS.includes(property))
        : []
      if (inBranch.length > 0) {
        return { conflict: `${name} offers the host-owned argument(s) ${inBranch.join(', ')} inside a ${key} branch.`
          + ' Those are envelope metadata a model may not state, and a branch cannot be trimmed without changing'
          + ' which forms of the call validate, so the advertised contract is refused rather than rewritten.' }
      }
    }
  }
  const properties = schema.properties !== null && typeof schema.properties === 'object' && !Array.isArray(schema.properties)
    ? schema.properties : undefined
  const required = Array.isArray(schema.required) ? schema.required.map(String) : undefined
  const owned = properties === undefined ? [] : Object.keys(properties).filter((key) => HOST_OWNED_TOOL_FIELDS.includes(key))
  const requiredOwned = (required ?? []).filter((key) => HOST_OWNED_TOOL_FIELDS.includes(key))
  if (requiredOwned.length > 0) {
    return { conflict: `${name} makes the host-owned argument(s) ${requiredOwned.join(', ')} required.`
      + ' Those are envelope metadata this host supplies and a model may not state, so the advertised'
      + ' contract cannot be satisfied by any call this client would carry.' }
  }
  if (owned.length === 0) return { schema, conflict: undefined }
  return {
    schema: {
      ...schema,
      properties: Object.fromEntries(Object.entries(properties).filter(([key]) => !HOST_OWNED_TOOL_FIELDS.includes(key))),
      ...(required === undefined ? {} : { required: required.filter((key) => !HOST_OWNED_TOOL_FIELDS.includes(key)) }),
    },
    conflict: undefined,
    stripped: owned,
  }
}

// `tools/list` may answer in pages; this bounds how many will be read before the endpoint
// is judged to be looping rather than paging.
const TOOLS_LIST_PAGES_MAX = 32
let mcpSurfacePromise
/** The six model-facing tools, in the order the authority names them. */
let modelTools = []

/**
 * Compare the advertised membership with the approved surface, and say exactly how they
 * differ.
 *
 * Membership is a contract, not a menu. The earlier version checked only for *missing*
 * names and then rebuilt the list from its own constant, so a server advertising a sixth
 * tool — or a renamed one, or the same one twice — was silently reinterpreted into a
 * surface it had not offered. That is a client unilaterally deciding what the server meant.
 * Extra, duplicated and retired names are now named in the refusal.
 */
function toolMembershipConflicts(tools) {
  const conflicts = []
  const seen = new Map()
  const duplicates = new Set()
  for (const tool of tools) {
    const name = String(tool?.name ?? '')
    if (name === '') continue
    if (seen.has(name)) duplicates.add(name)
    else seen.set(name, tool)
  }
  const missing = MODEL_TOOLS.filter((name) => !seen.has(name))
  const extra = [...seen.keys()].filter((name) => !MODEL_TOOLS.includes(name))
  const retired = extra.filter((name) => RETIRED_TOOL_NAMES.includes(name))
  if (missing.length > 0) conflicts.push(`it does not advertise ${missing.join(', ')}`)
  if (duplicates.size > 0) conflicts.push(`it advertises ${[...duplicates].join(', ')} more than once`)
  if (retired.length > 0) {
    conflicts.push(`it still advertises the retired host surface ${retired.join(', ')},`
      + ' which means this endpoint has not been cut over to the single-MCP contract')
  }
  const unknown = extra.filter((name) => !RETIRED_TOOL_NAMES.includes(name))
  if (unknown.length > 0) {
    conflicts.push(`it advertises ${unknown.join(', ')}, which is not part of the approved six-tool surface`)
  }
  return { conflicts, advertised: seen }
}

async function requirePublicMcpSurface() {
  mcpSurfacePromise ??= (async () => {
    // `tools/list` may answer in pages. Judging membership from the first page would read a
    // paged endpoint as one that does not advertise the tools it simply had not sent yet,
    // and the refusal would then name the wrong side. The pages are read to the end, with a
    // bound so that a server looping cursors cannot hold this client here forever.
    const tools = []
    let cursor
    for (let page = 0; page < TOOLS_LIST_PAGES_MAX; page++) {
      const listed = await mcpRpc('tools/list', cursor === undefined ? {} : { cursor }, { handshake: true })
      const meta = hostMetaOf(listed)
      if (typeof meta?.agentId === 'string' && meta.agentId.trim() !== '') agentId ||= meta.agentId.trim()
      absorbHostMeta(meta)
      if (Array.isArray(listed?.tools)) tools.push(...listed.tools)
      const next = listed?.nextCursor
      if (typeof next !== 'string' || next === '' || next === cursor) break
      cursor = next
      if (page + 1 === TOOLS_LIST_PAGES_MAX) {
        throw new McpSurfaceError(`The public MCP endpoint is still paging tools/list after ${TOOLS_LIST_PAGES_MAX} pages.`
          + ' The advertised surface cannot be read to the end, so this Runtime will not judge membership from part of it.')
      }
    }
    const { conflicts, advertised } = toolMembershipConflicts(tools)
    if (conflicts.length > 0) {
      throw new McpSurfaceError('The public MCP endpoint advertises a tool surface this Runtime cannot speak:\n'
        + conflicts.map((line) => `  · ${line}`).join('\n')
        + `\n  Advertised: ${[...advertised.keys()].join(', ') || '(none)'}`
        + `\n  Contract:   ${MODEL_TOOLS.join(', ')}`
        + `\n  This Runtime speaks the public MCP contract at commit ${RULITH_CONTRACT_SOURCE_COMMIT}.`
        + '\n  This is a protocol mismatch, not a filtering decision: a client that quietly reinterpreted'
        + ' the surface would be deciding on its own what the authority had offered. Upgrade the Cloud'
        + ' endpoint, or upgrade this Runtime, so that both sides name the same six tools.')
    }
    const schemaConflicts = []
    const projected = MODEL_TOOLS.map((name) => {
      const tool = advertised.get(name)
      const { schema, conflict, stripped } = projectToolSchema(name, tool.inputSchema ?? tool.input_schema)
      if (conflict !== undefined) { schemaConflicts.push(conflict); return undefined }
      if (stripped !== undefined) {
        console.error(`⚠ ${name}: the advertised schema offered the host-owned argument(s) ${stripped.join(', ')};`
          + ' they were not shown to the model. Host metadata belongs in the envelope, not in a tool schema.')
      }
      return { name, description: String(tool.description ?? `Rulith Board ${name}`).slice(0, 1024), schema }
    })
    if (schemaConflicts.length > 0) {
      throw new McpSurfaceError('The public MCP endpoint advertises tool schemas this Runtime cannot satisfy:\n'
        + schemaConflicts.map((line) => `  · ${line}`).join('\n'))
    }
    modelTools = projected
  })()
  return await mcpSurfacePromise
}

/**
 * The transport key, and the one call this host may not lose.
 *
 * A tool call is identified by **(Agent, MCP session, JSON-RPC request id)**. All three
 * parts matter, and the middle one is the part a previous version dropped: it keyed
 * unresolved submissions by body alone, so after a session ended and a new one was
 * established, the same body was re-sent under the *old* request id and the code told the
 * model that this reached "the same identity". It did not. Under a different session it is
 * a different transport key and therefore a different logical call, and a write that had
 * already landed could land again. That promise is gone, and so is the re-presentation
 * that relied on it.
 *
 * What replaces the ledger is one record, because there is one thing to remember: calls
 * are serial, so at most one can be unresolved at a time. Recording the session it was
 * sent under is what lets this host say "this cannot be re-presented" instead of
 * pretending it can.
 *
 * The record is not a second execution ledger. The authority holds the execution truth;
 * this is the local half of "I do not know", and it exists so that the unknown can be
 * named — at the next turn, at the next startup, and to an operator.
 */
const submissionKey = (value) => JSON.stringify(value, (_key, item) =>
  (item !== null && typeof item === 'object' && !Array.isArray(item)
    ? Object.fromEntries(Object.keys(item).sort().map((name) => [name, item[name]]))
    : item))

/** A fresh transport identity, bound to the session that will carry it. */
const newSubmission = (name, input) => ({
  requestId: randomUUID(),
  sessionId: connection.id,
  name,
  body: submissionKey(input),
  since: Date.now(),
})

/**
 * The identity of the mechanical handoff claim.
 *
 * Deliberately its own, and deliberately not derived from the request body. The claim is a
 * `QueryBoard` with the safe default — byte for byte what the model itself sends when it
 * wants the Case directory — so a body-derived identity made the two collide: the claim
 * inherited the model's in-flight request id, the authority answered it as a re-send of
 * that call, and the handoff never happened. A resend of the *claim* keeps this identity;
 * nothing else shares it.
 */
function claimIdentity() {
  // Re-minted when the session changes, for the same reason a submission is never
  // re-presented across one: the transport key includes the session, so the old id would be
  // a different call under the new one. A resend within the same session keeps the identity,
  // which is what makes a repeated claim hit the same handoff instead of a second one.
  if (board.claim === undefined || board.claim.sessionId !== connection.id) {
    board.claim = { requestId: randomUUID(), sessionId: connection.id, since: Date.now() }
  }
  return board.claim
}

/** Remember the call whose outcome is unknown, durably, and say so at the next startup. */
function holdUnresolved(record) {
  board.unresolved = record
  persistUnresolved()
}

function releaseUnresolved() {
  if (board.unresolved === undefined) return
  board.unresolved = undefined
  persistUnresolved()
}

// ── The Board View, as the authority returns it ─────────────────────────────
//
// Every tool result carries the profile-filtered Board View the authority computed for
// that operation. The host never reads the Board a second time to learn what just
// happened, and it ranks nothing locally: `status` per root and `gaps` are the
// authority's own words. A local ladder over them had to be edited whenever Core added a
// tier, and an unknown tier read as the weakest — a silent downgrade in the direction
// that looks safe.
const boardViewOf = (result) => {
  const payload = result?.payload
  if (payload !== null && typeof payload === 'object' && !Array.isArray(payload)) return payload
  return undefined
}
const viewText = (view) => (view === undefined ? '(no Board View was returned)' : JSON.stringify(view, null, 2))
/**
 * Root rows the authority reported.
 *
 * Both carriers are read, directory first: `roots` describes what this session is focused
 * on, and the bounded Case directory describes Cases beyond it — including the one that
 * just closed and therefore left focus. Reading only the first made a closed Case
 * indistinguishable from one that had merely been released.
 */
function reportedRootsOf(view) {
  const rows = [
    ...(Array.isArray(view?.cases?.directory) ? view.cases.directory : []),
    ...(Array.isArray(view?.roots) ? view.roots : []),
  ]
  return rows.filter((row) => row !== null && typeof row === 'object')
    .map((row) => ({
      caseId: String(row.caseId ?? ''),
      root: String(row.root ?? ''),
      status: LIFECYCLE.includes(row.status) ? String(row.status) : 'unavailable',
    }))
    .filter((row) => row.caseId !== '' || row.root !== '')
}
/**
 * Roots the authority declined to describe.
 *
 * The entry is deliberately neutral: it does not distinguish "never existed" from "deleted"
 * from "not visible to you", and neither does anything here. What matters locally is that
 * an unavailable root must *lose* whatever status it last had rather than keep it — a root
 * shown as running because the last answer that mentioned it said so is the same defect as
 * inventing a status outright, only slower.
 */
const unavailableRootsOf = (view) => (Array.isArray(view?.unavailableRoots)
  ? view.unavailableRoots.map(String).filter((root) => root !== '')
  : [])
const gapsOf = (view) => (Array.isArray(view?.gaps) ? view.gaps.length : undefined)

/**
 * Where the authority says a bounded view dropped rows.
 *
 * Core's published Board View reports truncation **per limb** (`cases.truncated` beside
 * `cases.total`) and once at the top level for the node limbs (`truncated` beside `total`).
 * An earlier version of this client read a single aggregate `loss` object that a Core draft
 * had proposed and the published schema does not contain — so against the real authority it
 * saw no truncation at all and presented a partial view as a complete one. Both published
 * carriers are read now, and `loss` is kept only as a tolerated alias in case it returns.
 *
 * Returns the limbs that were truncated, or an empty array. Nothing is inferred from a
 * missing `truncated`: absent means the authority did not say it truncated, which is the
 * ordinary case and not a claim of completeness by this client.
 */
function truncatedLimbsOf(view) {
  const limbs = []
  if (view?.cases?.truncated === true) {
    limbs.push({ limb: 'cases', total: Number.isFinite(view.cases.total) ? Number(view.cases.total) : undefined })
  }
  if (view?.truncated === true) {
    limbs.push({ limb: 'nodes', total: Number.isFinite(view?.total) ? Number(view.total) : undefined })
  }
  const loss = view?.loss
  if (loss !== null && typeof loss === 'object' && loss.truncated === true) {
    limbs.push({ limb: 'view', total: Number.isFinite(loss.omitted) ? Number(loss.omitted) : undefined, reason: String(loss.reason ?? 'limit') })
  }
  return limbs
}
const viewIsTruncated = (view) => truncatedLimbsOf(view).length > 0

/** The lifecycle words the authority uses. Anything else is `unavailable`, never guessed. */
const LIFECYCLE = ['running', 'paused', 'closed']
const TERMINAL_LIFECYCLE = new Set(['closed'])
const liveRootsOf = (ctx) => board.roots.filter((row) => row.status === 'running')

/**
 * The recovery state, as the authority publishes it.
 *
 * `state` is the required field and the only one with a closed set of values; everything
 * else describes an outstanding call and may be absent. Values outside the set are dropped
 * rather than guessed at: an unrecognised state read as `none` would let a host with an
 * unresolved call carry on as though there were none, which is the precise defect the
 * whole serial gate exists to prevent. An unreadable state therefore blocks.
 */
function recoveryOf(meta) {
  const recovery = meta?.recovery
  if (recovery === null || typeof recovery !== 'object' || Array.isArray(recovery)) {
    // The record is required on the two carriers that publish it. Absent is not `none`:
    // `none` is the authority saying there is nothing outstanding, and absent is this host
    // having no idea — which is the same position as an unreadable state and gets the same
    // answer, because the alternative is proceeding on an assumption.
    return { state: 'unreadable',
      teaching: 'The authority published no recovery record, so whether a call is outstanding for this Agent is unknown.' }
  }
  const state = String(recovery.state ?? '')
  if (!RECOVERY_STATES.has(state)) {
    return { state: 'unreadable', teaching: `The authority published recovery state ${JSON.stringify(recovery.state)}, which this Runtime does not understand.` }
  }
  const positive = (value) => (Number.isFinite(value) && value >= 0 ? Number(value) : undefined)
  return {
    state,
    ...(typeof recovery.callRef === 'string' && recovery.callRef !== '' ? { callRef: recovery.callRef } : {}),
    ...(MODEL_TOOLS.includes(recovery.tool) ? { tool: recovery.tool } : {}),
    ...(typeof recovery.since === 'string' && recovery.since !== '' ? { since: recovery.since } : {}),
    ...(positive(recovery.retryAfterMs) === undefined ? {} : { retryAfterMs: positive(recovery.retryAfterMs) }),
    ...(typeof recovery.teaching === 'string' && recovery.teaching !== '' ? { teaching: recovery.teaching } : {}),
  }
}

/**
 * The handoff marker: this tool result carries an *earlier* call's outcome, not this one's.
 *
 * Two independent signals have to agree, and both are load-bearing. `isError` on the tool
 * result is the protocol-level statement that the request was refused rather than served,
 * and `requestExecuted: false` in the metadata is the Rulith-level statement of what was
 * refused and whose outcome came instead. A result that carries one without the other is
 * not a handoff — it is a server contradicting itself about whether the model's call ran,
 * and the caller turns that into an unknown outcome rather than picking a side.
 */
function handoffOf(meta, isError) {
  const handoff = meta?.handoff
  if (handoff === null || typeof handoff !== 'object' || Array.isArray(handoff)) return undefined
  if (handoff.requestExecuted !== false) return undefined
  if (isError !== true) return undefined
  return {
    ...(typeof handoff.callRef === 'string' && handoff.callRef !== '' ? { callRef: handoff.callRef } : {}),
    ...(MODEL_TOOLS.includes(handoff.tool) ? { tool: handoff.tool } : {}),
    requestExecuted: false,
  }
}

/**
 * Take what the authority said about identity, focus and recovery — and nothing the model
 * or a previous run said.
 *
 * `focusedRoots` is the authoritative membership of this session's focus; the runtime never
 * derives a {caseId, root} pair itself. `boardRevision` is an audit string: it locates a
 * displayed view in the commit order and is never presented back as a precondition.
 */
function absorbHostMeta(meta) {
  if (meta === undefined) return undefined
  // Every `rulith/v1` block carries the record — the metadata schema makes it required of
  // all of them, not only of `ping` and `initialize` — so a block that arrives without one
  // is read the same way a missing one is anywhere else: unreadable, and therefore a reason
  // to stop rather than a reason to keep the last state. Letting silence mean "as you were"
  // would be the same assumption this gate exists to refuse, made one carrier further out.
  connection.recovery = recoveryOf(meta)
  return meta
}

/** Focus pairs are Core-derived. An entry the authority did not return is not focus. */
function focusPairsOf(meta) {
  if (!Array.isArray(meta?.focusedRoots)) return undefined
  return meta.focusedRoots
    .filter((pair) => pair !== null && typeof pair === 'object')
    .map((pair) => ({ caseId: String(pair.caseId ?? ''), root: String(pair.root ?? '') }))
    .filter((pair) => pair.caseId !== '' && pair.root !== '')
}

// ── Local Case observations ─────────────────────────────────────────────────
//
// Lifecycle is the Board's, and it is distinct from conversation progress: a model that
// stopped talking has not paused a Case, and a conversation that was reclaimed has not
// closed one. Every observation below comes from something the authority returned.
function observeRoot(ctx, row, contact = 'observed') {
  const observation = {
    caseId: row.caseId, root: row.root, caseStatus: row.status,
    ...(typeof row.gaps === 'number' ? { gaps: row.gaps } : {}),
    ...(contact === 'observed' ? {} : { contact }),
  }
  const identity = JSON.stringify(observation)
  if (board.lastRootObservation.get(row.caseId) === identity) return
  board.lastRootObservation.set(row.caseId, identity)
  while (board.lastRootObservation.size > 64) board.lastRootObservation.delete(board.lastRootObservation.keys().next().value)
  emitOn(ctx, 'case-state', observation)
}

/** Publish the focus set itself, so Local can show several roots rather than one. */
function publishFocus(ctx) {
  const identity = JSON.stringify(board.roots)
  if (board.lastFocusPublished === identity) return
  board.lastFocusPublished = identity
  emitOn(ctx, 'focus', { roots: board.roots.map((row) => ({ caseId: row.caseId, root: row.root, status: row.status })) })
}

/**
 * Reconcile this conversation's focus with what the authority just reported.
 *
 * Membership comes from `focusedRoots`; status comes from the Board View's own root rows.
 * Three states are kept apart, because collapsing any two of them is a way of showing a
 * number the authority did not say:
 *
 *   · **refreshed** — this answer described the root. It is observed, now.
 *   · **unavailable** — the authority listed the root in `unavailableRoots`. It loses
 *     whatever status it had; that is a statement, not an absence.
 *   · **not refreshed** — the answer was bounded and simply did not reach this root. The
 *     previous status is retained but is no longer an observation of the present, so it is
 *     republished as `contact: 'not-refreshed'` rather than passed back through as if the
 *     authority had just confirmed it.
 *
 * Roots leave focus only because the authority stopped listing them; leaving focus is not
 * itself a lifecycle transition, and only an observed terminal status closes a Case.
 */
function trackFocus(ctx, meta, view, command) {
  const pairs = focusPairsOf(meta)
  const reported = new Map(reportedRootsOf(view).map((row) => [row.caseId || row.root, row]))
  const unavailable = new Set(unavailableRootsOf(view))
  const truncated = viewIsTruncated(view)
  const gaps = gapsOf(view)
  const previous = new Map(board.roots.map((row) => [row.caseId, row]))
  /** `{ status, contact }` — never a bare status, so the caller cannot lose the distinction. */
  const stateOf = (caseId, root, before) => {
    if (unavailable.has(root)) return { status: 'unavailable', contact: 'observed' }
    const seen = reported.get(caseId) ?? reported.get(root)
    if (seen !== undefined && seen.status !== 'unavailable') return { status: seen.status, contact: 'observed' }
    if (before?.status !== undefined && truncated) return { status: before.status, contact: 'not-refreshed' }
    if (before?.status !== undefined && seen === undefined) return { status: before.status, contact: before.contact ?? 'not-refreshed' }
    return { status: 'unavailable', contact: 'observed' }
  }
  if (pairs !== undefined) {
    board.roots = pairs.map((pair) => {
      const before = previous.get(pair.caseId)
      const { status, contact } = stateOf(pair.caseId, pair.root, before)
      return { caseId: pair.caseId, root: pair.root, status, contact,
        ...(before?.caseType === undefined ? {} : { caseType: before.caseType }) }
    })
  } else {
    // No focus statement: keep membership and refresh only what this answer described.
    board.roots = board.roots.map((row) => {
      const { status, contact } = stateOf(row.caseId, row.root, row)
      return { ...row, status, contact }
    })
  }
  for (const row of board.roots) {
    // `gaps` is one count over the view, not a per-root figure. With a single focused root
    // the attribution is unambiguous; with several it would be a number attached to a root
    // it does not describe, so it is left off rather than divided or repeated. A root this
    // answer did not refresh gets no gap count at all: the number would be from elsewhere.
    const fresh = row.contact === 'observed'
    observeRoot(ctx, { ...row, ...(fresh && board.roots.length === 1 && typeof gaps === 'number' ? { gaps } : {}) },
      row.contact ?? 'observed')
  }
  for (const [caseId, before] of previous) {
    if (board.roots.some((row) => row.caseId === caseId)) continue
    const seen = reported.get(caseId) ?? reported.get(before.root)
    if (seen !== undefined && TERMINAL_LIFECYCLE.has(seen.status)) {
      observeRoot(ctx, seen)
      // The disposition is the one this host sent on the accepted CloseCase — a fact it
      // knows — not a `receipt.disposition` read back out of the result. Core's published
      // result envelope has no such field, so reading one meant printing "closed" for every
      // close regardless of what was actually asked for.
      const asked = command?.name === 'CloseCase' ? String(command.input?.disposition ?? '').trim() : ''
      const disposition = asked === '' ? 'closed' : asked
      log(`◎ Closed Case "${caseId}" with disposition "${disposition}". Its record remains available in Console.`)
      emitOn(ctx, 'case-closed', { caseId, root: before.root, disposition })
      continue
    }
    // Focus loss without an observed terminal status says nothing about the lifecycle.
    emitOn(ctx, 'case-unfocused', { caseId, root: before.root })
  }
  publishFocus(ctx)
}

/**
 * Say out loud when a bounded read dropped rows.
 *
 * The authority marks truncation explicitly precisely so that it is not silent. The model
 * already sees it — the marker is inside the Board View it was handed — but a person
 * watching Local would otherwise read a partial answer as a complete one, and so would the
 * focus reconciliation above if it did not know the view was bounded.
 */
function reportLoss(ctx, name, view) {
  const limbs = truncatedLimbsOf(view)
  if (limbs.length === 0) return
  const described = limbs.map((limb) => `${limb.limb}${limb.total === undefined ? '' : ` (${limb.total} total)`}`).join(', ')
  const note = `${name} returned a bounded view: ${described} was truncated by the authority. This answer is partial;`
    + ' anything it does not mention is unreported, not absent.'
  log(`◌ ${note}`)
  emitOn(ctx, 'loss', { cmd: name, limbs: limbs.map((limb) => limb.limb), ...(limbs[0].reason === undefined ? {} : { reason: limbs[0].reason }) })
}

/**
 * Outcomes that are unknown rather than refused.
 *
 * They differ in where the knowledge was lost — the hop, this client's own read limit, or
 * a peer that answered something other than the answer to this request — and the model is
 * told which, because "retry unchanged" is right for all three but "why" is not the same
 * story. What they share is the only thing the loop reasons about: nobody here knows what
 * the Board did, so the request identity is held and the step is not judged failed.
 */
/** Every local refusal wears the same envelope the Board's own refusals wear, so the
 *  model never has to tell "the host would not carry this" from "the Board said no" by
 *  the shape of the answer — the errorCode says which. */
const refusal = (errorCode, teaching) => JSON.stringify({ accepted: false, errorCode, teaching })

const AMBIGUOUS_OUTCOMES = new Set(['upstream_unavailable', 'response_too_large', 'response_not_correlated', 'session_expired'])
const transportAmbiguous = (value) => AMBIGUOUS_OUTCOMES.has(String(value?.errorCode ?? ''))
const AMBIGUITY_CAUSE = {
  upstream_unavailable: 'The hop to the authority failed, so no receipt was returned.',
  response_too_large: 'The hop succeeded, but the answer exceeded this client\'s local response limit and was not read.'
    + ' The command may well have been applied.',
  response_not_correlated: 'The hop succeeded, but what came back was not the answer to this request, so it was discarded.'
    + ' The command may well have been applied.',
  session_expired: 'The transport session ended before the answer arrived. The command may well have been applied.',
}
/**
 * What the model is told about an unknown outcome — and what it is *not* told.
 *
 * It used to end with "retry the identical step". That instruction is now wrong in the one
 * way that matters: while a call is unresolved this host may not send another tool call at
 * all, so a model acting on it would be proposing something that cannot be carried. The
 * authority holds the original call, this host recovers it, and only a determined result —
 * handed over as a handoff — is a basis for deciding again.
 */
const transportUnknownTeaching = (value) => `${AMBIGUITY_CAUSE[String(value?.errorCode ?? '')] ?? 'No authoritative Board receipt was returned.'}`
  + ' The outcome of this step is unknown. This is not a refusal. The original call keeps its identity **at the authority**,'
  + ' which is where it will be settled; that identity is not something a later request can reach. Anything you choose next'
  + ` is a new command, so treat this step's effect as unknown rather than as undone. ${String(value?.teaching ?? '').slice(0, 320)}`

/**
 * Did the authority actually answer, in the shape this tool answers in?
 *
 * The two targets answer differently and neither shape may be imposed on the other. A Board
 * operation returns the Core result envelope, so `accepted` or an `errorCode` is what makes
 * it a receipt. `ReadArtifact` returns a data fragment from the Gateway's result plane:
 * requiring `accepted` there would have read every successful artifact read as "no receipt"
 * and marked a read that plainly succeeded as an unknown outcome.
 *
 * A handoff is the third case, and its caller has already recognised it: its content
 * belongs to the tool that originally ran, whose shape this request's own name says
 * nothing about, so this function is not consulted for one.
 */
function looksAuthoritative(name, result) {
  if (result === undefined) return false
  if (typeof result.errorCode === 'string') return true
  if (BOARD_TOOLS.has(name)) return typeof result.accepted === 'boolean'
  return typeof result.ref === 'string' && result.ref !== ''
}

/**
 * Call one advertised tool the way any MCP client would.
 *
 * Nothing of this host's own travels in the arguments and nothing travels beside them: the
 * protected query context is the Gateway's to inject from the authenticated principal, the
 * session is a transport header, and the request identity is the JSON-RPC id. A client
 * that supplied `audienceProfile` would be asking to be read as somebody else.
 *
 * Nothing is fetched first either. A write never begins with a read: the authority judges
 * each command against the premises, grounding and policy in force when it executes.
 */
async function callTool(ctx, name, input, { claim = false } = {}) {
  await openSession()
  await requirePublicMcpSurface()
  // The serial gate, checked rather than assumed. Every caller is supposed to have settled
  // the outstanding call first — the model loop, `--case`, the shadow reviewer — and this
  // is the one place that can prove none of them slipped past. A second call issued while
  // the first outcome is unknown is the defect the whole gate exists to prevent, so it is
  // refused here even if some future caller forgets, and it says which call is holding.
  if (!claim && board.unresolved !== undefined) {
    const held = board.unresolved
    const teaching = `${name} was not sent: this Agent has an unresolved ${held.name} call (request ${held.requestId})`
      + ' and sends nothing further until the authority settles it. Calls are serial for the whole Agent, not per conversation.'
    log(`✗ ${teaching}`)
    emitOn(ctx, 'verdict', { accepted: false, cmd: name, teaching, refusedLocally: true })
    return { result: { accepted: false, errorCode: 'call_gate_open', teaching },
      text: refusal('call_gate_open', teaching), authoritative: false, view: undefined, refusedLocally: true }
  }
  const identity = claim ? claimIdentity() : newSubmission(name, input)
  let result
  let text = ''
  let handoffText
  let hostMeta
  let isError = false
  let authoritative = true
  try {
    const answer = await mcpRpc('tools/call', { name, arguments: input }, { id: identity.requestId })
    // Host metadata and model content are two channels. The text is the authority's own
    // JSON; `_meta` never enters it.
    hostMeta = hostMetaOf(answer)
    isError = answer?.isError === true
    text = (Array.isArray(answer?.content) ? answer.content : [])
      .filter((item) => item?.type === 'text').map((item) => String(item.text ?? '')).join('\n')
    if (text === '') throw new Error(`MCP tool ${name} returned no text result.`)
    try { result = JSON.parse(text) } catch { result = undefined }
    if (result === null || typeof result !== 'object' || Array.isArray(result)) result = undefined
  } catch (error) {
    if (error instanceof AgentCredentialRejectedError) throw error
    if (error instanceof McpSurfaceError) throw error
    if (error instanceof McpConnectionReplacedError) throw error
    authoritative = false
    // Four different unknowns, said as four different things. All of them leave the
    // outcome unknown and the identity held, but a reader debugging "the write vanished"
    // needs to know whether the hop failed, whether this client refused to read the
    // answer, whether the peer answered something else entirely, or whether the transport
    // session ended underneath it.
    result = {
      accepted: false,
      errorCode: error instanceof McpResponseLimitError ? 'response_too_large'
        : error instanceof McpCorrelationError ? 'response_not_correlated'
          : error instanceof McpSessionExpiredError ? 'session_expired'
            : 'upstream_unavailable',
      teaching: String(error?.message ?? error).slice(0, 320),
    }
    if (error instanceof McpSessionExpiredError) {
      // The session is gone, so the next contact must initialize a new one. That is a
      // transport fact and not a licence to re-send: the transport key includes the
      // session, so this call cannot be re-presented at all. What became of it is answered
      // by the new session's recovery state.
      connection.id = undefined
      connection.ready = false
      connection.opening = undefined
      connection.lastEventId = undefined
    }
  }
  const handoff = handoffOf(hostMeta, isError)
  // A handoff marker without `isError` is two channels disagreeing about whether this
  // request ran. Neither may be believed over the other, so the outcome is unknown — the
  // one reading that cannot turn "your write did not execute" into "your write succeeded".
  if (handoff === undefined && hostMeta?.handoff !== undefined) {
    authoritative = false
    result = { accepted: false, errorCode: 'handoff_malformed',
      teaching: `${name} came back with a handoff marker but was not marked as an error result, so whether it executed is not known.` }
  }
  if (handoff === undefined && !looksAuthoritative(name, result)) {
    authoritative = false
    result = { accepted: false, errorCode: 'upstream_unavailable', teaching: `${name} returned no authoritative receipt.` }
  }
  // The Gateway can return an MCP result with an ambiguity code after losing the Core
  // response: a successful HTTP/MCP hop is not itself a Board receipt.
  if (transportAmbiguous(result)) authoritative = false
  if (authoritative) {
    if (claim) board.claim = undefined
    else releaseUnresolved()
  }
  if (authoritative) {
    absorbHostMeta(hostMeta)
    if (handoff !== undefined) {
      // **The request did not run.** What came back is an earlier call's outcome, and the
      // two must not be allowed to read as one: handing this result back unlabelled told
      // the model its `ApplyBatch` had been accepted when the acceptance belonged to an
      // `ApplyAction` from another turn. The earlier outcome is kept whole, as data, under
      // a name that says whose it is; the envelope says this call executed nothing.
      handoffText = text
      // The parsed earlier outcome, taken before `result` is replaced. Re-parsing the text
      // here would throw on a body that is not JSON — and a malformed handoff is a thing to
      // report, not a thing to crash on.
      const earlier = result
      const from = handoff.tool ?? 'an earlier'
      // Both channels, not just the one the model reads. Rewriting `text` alone left
      // `result` pointing at the earlier call's verdict, and every caller that judged by
      // `result.accepted` — `focusExistingCase`, the shadow reviewer — read an acceptance
      // that belonged to a different call and announced something that had not happened.
      // One value, one meaning: the envelope says this request did not run, and the earlier
      // outcome leaves only under a name that says whose it is.
      result = {
        accepted: false,
        errorCode: 'request_not_executed',
        requestExecuted: false,
        handedOverFrom: handoff.tool ?? null,
        teaching: `${name} was not executed. Before it could run, the authority handed back the outcome of an earlier ${from} call`
          + ' from this Agent that had been determined but not yet delivered. Read that outcome, then decide again —'
          + ' nothing has been re-sent on your behalf, and this request changed nothing.',
        // Whole, under a name that says whose it is. A body this client could not parse is
        // still handed over — as text, said to be text — rather than silently dropped.
        ...(earlier === undefined ? { earlierResultText: handoffText.slice(0, 8000) } : { earlierResult: earlier }),
      }
      text = JSON.stringify(result)
      // The claim's own outcome is not this call's: what it delivered belongs to the call
      // named in the marker, and that is the one whose record can now be closed.
      releaseUnresolved()
    } else if (BOARD_TOOLS.has(name)) {
      trackFocus(ctx, hostMeta, boardViewOf(result), { name, input })
      // `affectedCases` is complete and causal, and the empty array is a statement: no live
      // root advanced. Reporting it only when non-empty would erase the difference between
      // "nothing was affected" and "the authority did not say".
      if (Array.isArray(hostMeta?.affectedCases)) {
        emitOn(ctx, 'affected', { cmd: name, affectedCases: hostMeta.affectedCases.map(String) })
      }
      reportLoss(ctx, name, boardViewOf(result))
    }
  } else {
    text = JSON.stringify({ ...result, teaching: transportUnknownTeaching(result) })
    for (const row of board.roots) observeRoot(ctx, row, 'unknown')
    // The one call whose outcome this host does not know. Calls are serial for the whole
    // Agent, so there is at most one; it is held, named and persisted until the authority
    // says what became of it, and it is never re-presented under another session.
    if (!claim) holdUnresolved(identity)
  }
  const view = handoff === undefined && BOARD_TOOLS.has(name) ? boardViewOf(result) : undefined
  if (view !== undefined) board.lastView = view
  // An authoritative refusal is not retried here. The step the model chose was judged by
  // the authority against the premises and policy in force, and re-sending it with the
  // refusal's own words attached would be this host deciding on the model's behalf.
  return { result, text, handoffText, authoritative, view, isError, handoff, recovery: connection.recovery }
}

// ── Recovery: one unresolved call, settled by the authority before anything else ──
//
// The product rule this implements is short and unforgiving: while one call is unresolved,
// this Agent runs no model turn and sends no tool call — not a write, not `QueryBoard`,
// not `ReadArtifact`. The host waits, and the authority says what to wait for.
//
// The waiting is done with the base protocol's own `ping`: it returns immediately, reads no
// Board, changes no focus and carries no business data, and Rulith attaches the recovery
// record to its `_meta`. That is why there is no extra model tool and no polling loop the
// model can see — a model told to "check again" is a model spending turns on transport.
//
// The four states and the mechanical answer to each:
//
//   · `none`                     — nothing outstanding; work may proceed.
//   · `waiting`                  — the call is still executing. Wait, do not ask the model.
//   · `result_ready`             — the outcome is determined and undelivered. Collect it
//                                  with exactly one claim, then let the model decide again.
//   · `reconciliation_required`  — an operator has to reconcile the original call. Stop
//                                  recovering automatically and say where that happens.
const RECOVERY_WAIT_MS = envNumber('RULITH_RECOVERY_WAIT_MS', 120_000, { min: 0, max: 86_400_000 })
const RECOVERY_POLL_MS = envNumber('RULITH_RECOVERY_POLL_MS', 1000, { min: 50, max: 60_000 })
const RECOVERY_POLL_MIN_MS = 250
const RECOVERY_POLL_MAX_MS = 10_000
// Deliberately not `unref`'d: this wait *is* the work. An unreferenced timer would let the
// process decide it had nothing left to do and exit while a call was still outstanding.
const sleep = (ms) => new Promise((wake) => { setTimeout(wake, ms) })

/**
 * Read the recovery record over `ping`.
 *
 * Nothing is defaulted. An endpoint that answers `ping` without the record has not told
 * this host that there is nothing outstanding, and reading silence as `none` is exactly
 * how a host with an unresolved call walks into the handoff it was supposed to collect.
 */
async function pingRecovery() {
  await openSession()
  const result = await mcpRpc('ping', {}, { timeoutMs: 15_000 })
  const recovery = recoveryOf(hostMetaOf(result))
  connection.recovery = recovery
  return recovery
}

/** How long to wait before the next `ping`, from the authority's hint, bounded locally. */
const pollDelayOf = (recovery) => Math.min(RECOVERY_POLL_MAX_MS,
  Math.max(RECOVERY_POLL_MIN_MS, recovery.retryAfterMs ?? RECOVERY_POLL_MS))

/**
 * The one sentence the model is given when an earlier call's outcome is handed over.
 *
 * It is a host-recovery note in the user channel, and it says so. Two shapes were rejected
 * deliberately: an `assistant` tool_call this model never made — which would put words in
 * its mouth and invite it to "continue" a step it never chose — and a plain user message,
 * which would read as the operator saying something they did not say. The model is told
 * what ran, what did not, and that the next move is its own.
 */
const handoffNote = (tool, text) => `[Host recovery — this is not a message from the user, and not a tool call you made.]
The authority had already determined the outcome of an earlier ${tool ?? 'tool'} call from this Agent, and this host collected it before doing anything else.
The request that collected it executed nothing: no Board read, no write, and no Action ran for it.

Outcome of that earlier ${tool ?? 'tool'} call:
${text}

Decide again from here. Nothing has been re-sent on your behalf, and any step you still want must be proposed as a new one.`

/**
 * Collect a determined result with exactly one claim.
 *
 * The claim is an ordinary `tools/call` — a `QueryBoard` with the safe default — and the
 * authority answers it as an error tool result carrying the *earlier* call's outcome. The
 * claim itself does not execute, which is why an ordinary tool is safe to use for it and
 * why a fresh recovery-only tool would have been a worse answer: it would have added a
 * seventh name to the model's surface for a step the model never takes.
 */
async function claimHandoff(ctx, recovery) {
  emitOn(ctx, 'recovery', { state: 'result_ready', ...(recovery.tool === undefined ? {} : { tool: recovery.tool }),
    ...(recovery.callRef === undefined ? {} : { callRef: recovery.callRef }) })
  const answer = await callTool(ctx, 'QueryBoard', {}, { claim: true })
  const handoff = answer.handoff
  if (handoff === undefined) {
    // The authority answered the claim as an ordinary query while it still owed a result.
    // Reporting that as a successful handoff would lose the earlier outcome silently, so
    // it is said out loud and the caller re-reads the recovery state.
    console.error('⚠ The recovery claim was answered as an ordinary QueryBoard rather than as a handoff of the earlier call.'
      + ' The earlier outcome has not been delivered to this host.')
    emitOn(ctx, 'recovery', { state: 'claim_not_honoured' })
    return undefined
  }
  const tool = handoff.tool ?? recovery.tool
  // The outcome is known now, so the record this host was holding open is closed. (The
  // claim's own delivery already did this; doing it here as well is how the mechanical and
  // model-initiated paths stay one behaviour rather than two.)
  releaseUnresolved()
  log(`◎ Recovered the outcome of an earlier ${tool ?? 'tool'} call. This request executed nothing; the model decides again.`)
  emitOn(ctx, 'handoff', { ...(tool === undefined ? {} : { tool }),
    ...(handoff.callRef === undefined ? {} : { callRef: handoff.callRef }) })
  return { tool, text: answer.handoffText ?? answer.text }
}

/**
 * Settle whatever the authority is holding, before the model is asked anything.
 *
 * Returns `{ ok: true }` when work may proceed, optionally with the handoff note to put in
 * front of the model; `{ ok: false, teaching }` when it may not. It never returns "probably
 * fine": a state this host cannot read blocks, because carrying on with an unresolved call
 * is how one logical command becomes two.
 */
async function settleRecovery(ctx, { force = false } = {}) {
  // The handshake already published a recovery state, and every tool result republishes it,
  // so a host that knows there is nothing outstanding does not ask again. That is not an
  // optimisation for its own sake: an ordinary greeting must reach the model without this
  // Runtime making a single call it does not need, and a `ping` per turn would be exactly
  // such a call. `force` is for the case where the last thing that happened destroyed this
  // host's knowledge — a call whose outcome it never learned.
  try {
    await openSession()
  } catch (error) {
    if (error instanceof McpConnectionReplacedError) throw error
    if (error instanceof AgentCredentialRejectedError) throw error
    // No authenticated connection means no way to learn what is outstanding, and no licence
    // to guess. Nothing has been sent, and nothing will be until there is one.
    return { ok: false, state: 'unreachable',
      teaching: `No authenticated connection could be established to settle this Agent's work: ${String(error?.message ?? error).slice(0, 240)}`
        + ' Nothing was sent. Any earlier call keeps its identity at the authority.' }
  }
  // Nothing to settle only when the authority has said so *and* this host is not holding a
  // call of its own. Those two can disagree, and the disagreement is the important case:
  // see the `none` branch below.
  if (!force && board.unresolved === undefined
    && connection.recovery !== undefined && connection.recovery.state === 'none') return { ok: true }
  const deadline = Date.now() + RECOVERY_WAIT_MS
  let announced = ''
  for (;;) {
    let recovery
    try {
      recovery = await pingRecovery()
    } catch (error) {
      if (error instanceof McpConnectionReplacedError) throw error
      if (error instanceof AgentCredentialRejectedError) throw error
      if (Date.now() >= deadline) {
        return { ok: false, state: 'unreachable',
          teaching: `The authority could not be reached to settle this Agent's outstanding call: ${String(error?.message ?? error).slice(0, 200)}`
            + ' Nothing was sent. The earlier call keeps its identity; resolve it in Console if it does not settle.' }
      }
      await sleep(pollDelayOf({}))
      continue
    }
    if (recovery.state === 'none') {
      if (board.unresolved === undefined) {
        if (announced !== '') emitOn(ctx, 'recovery', { state: 'none' })
        return { ok: true }
      }
      // The authority has no outstanding call, and this host has one whose outcome it never
      // learned. That is not "it never happened": the transport failed after the request
      // left, and the absence of a Gateway record is a statement about the Gateway's
      // records, not about the world. Guessing either way is the one thing that must not
      // happen here, so it stops and names the call for a person to reconcile.
      const held = board.unresolved
      emitOn(ctx, 'recovery-conflict', { tool: held.name, requestId: held.requestId })
      return { ok: false, state: 'unreconciled',
        teaching: `This host is holding a ${held.name} call (request ${held.requestId}${held.sessionId === undefined ? '' : `, session ${held.sessionId}`})`
          + ' whose outcome it never learned, and the authority reports nothing outstanding for this Agent.'
          + ' The two cannot both be acted on: an empty recovery record does not prove the command had no effect, and this host'
          + ' will not re-send it under a new transport identity to find out. Reconcile that request in Console.'
          + `${SESSION_STORE_PATH === '' ? '' : ` The local record is in ${SESSION_STORE_PATH}; clear it once the request has been reconciled.`}` }
    }
    if (recovery.state === 'reconciliation_required') {
      emitOn(ctx, 'recovery', { state: recovery.state, ...(recovery.tool === undefined ? {} : { tool: recovery.tool }),
        ...(recovery.callRef === undefined ? {} : { callRef: recovery.callRef }) })
      return { ok: false, state: recovery.state,
        teaching: `An earlier ${recovery.tool ?? 'tool'} call from this Agent needs operator reconciliation before work continues.`
          + ` ${recovery.teaching ?? 'Its outcome is unknown to this host and will not be guessed.'}`
          + ' Automatic recovery has stopped. Reconcile the original call in Console; the effects it may have had are not cancelled by waiting.' }
    }
    if (recovery.state === 'unreadable') {
      emitOn(ctx, 'recovery', { state: 'unreadable' })
      return { ok: false, state: recovery.state,
        teaching: `${recovery.teaching} This host will not proceed while it cannot tell whether a call is outstanding.` }
    }
    if (recovery.state === 'result_ready') {
      const handoff = await claimHandoff(ctx, recovery)
      if (handoff !== undefined) return { ok: true, note: handoffNote(handoff.tool, handoff.text) }
      if (Date.now() >= deadline) {
        return { ok: false, state: 'handoff_unavailable',
          teaching: 'The authority reports a determined result for an earlier call but did not hand it over.'
            + ' No new work was started. Inspect the original call in Console.' }
      }
      await sleep(pollDelayOf(recovery))
      continue
    }
    // waiting
    if (announced !== 'waiting') {
      announced = 'waiting'
      log(`◌ An earlier ${recovery.tool ?? 'tool'} call is still executing at the authority. Waiting for it; the model is not being asked anything`
        + ' and no other tool call will be sent until it settles.')
      emitOn(ctx, 'recovery', { state: 'waiting', ...(recovery.tool === undefined ? {} : { tool: recovery.tool }),
        ...(recovery.callRef === undefined ? {} : { callRef: recovery.callRef }),
        ...(recovery.since === undefined ? {} : { since: recovery.since }) })
    }
    if (Date.now() >= deadline) {
      return { ok: false, state: 'waiting',
        teaching: `An earlier ${recovery.tool ?? 'tool'} call from this Agent is still unresolved after the local wait window.`
          + ' The call is still live at the authority and keeps its identity; this host stopped waiting, it did not cancel anything.'
          + ' Watch it in Console, or reconnect later — the outcome will be handed over then.' }
    }
    await sleep(pollDelayOf(recovery))
  }
}

// ── Model client (your key, straight to your model service; Rulith never sees it) ──
//
// Native tool use is the model surface. The schemas the authority advertises are the
// templates, so this runtime never writes a second grammar for the model to get subtly
// wrong — the last one was a fenced-JSON dialect whose templates the client's own parser
// could not read back, and four real runs dispatched nothing at all.
//
// Two provider shapes are spoken directly: Anthropic Messages (`tools` with
// `input_schema`, `tool_use` blocks, `tool_result` replies) and OpenAI Chat Completions
// (`tools` with `function.parameters`, `tool_calls`, role `tool` replies). An endpoint
// that rejects `tools` outright gets the emulated transport: the same schemas rendered
// into the system prompt, one JSON object read back as one call. That is a transport,
// not a second surface — the names, the schemas and the refusals are identical.
const MAIN_CFG = { url: MODEL_URL, key: MODEL_KEY, model: MODEL }
const SHADOW_CFG = {
  url: process.env.RULITH_SHADOW_URL ?? MODEL_URL,
  key: process.env.RULITH_SHADOW_KEY ?? MODEL_KEY,
  model: process.env.RULITH_SHADOW_MODEL ?? MODEL,
}
const openaiStyle = (cfg) => /\/chat\/completions\/?$/.test(cfg.url)
/** Emulation is sticky once chosen: a mixed transcript is a malformed one. */
let emulatedTools = (process.env.RULITH_MODEL_TOOLS ?? '') === 'emulated'
let emulatedSeq = 0

// The transcript is kept in one neutral shape and rendered per provider at send time.
// Holding provider-shaped messages instead would make the fallback below unusable: the
// turns already recorded in one dialect cannot be replayed in another.
const userEntry = (text) => ({ role: 'user', text: String(text) })
const assistantEntry = (text, toolCalls = []) => ({ role: 'assistant', text: String(text ?? ''), toolCalls })
const resultsEntry = (results) => ({ role: 'tool_results', results })

function renderMessages(entries, style) {
  const out = []
  for (const entry of entries) {
    if (entry.role === 'user') {
      out.push(style === 'anthropic' ? { role: 'user', content: [{ type: 'text', text: entry.text }] } : { role: 'user', content: entry.text })
      continue
    }
    if (entry.role === 'assistant') {
      const calls = Array.isArray(entry.toolCalls) ? entry.toolCalls : []
      if (style === 'anthropic') {
        const content = []
        if (entry.text !== '') content.push({ type: 'text', text: entry.text })
        for (const call of calls) content.push({ type: 'tool_use', id: call.id, name: call.name, input: call.input ?? {} })
        out.push({ role: 'assistant', content: content.length > 0 ? content : [{ type: 'text', text: '(no content)' }] })
        continue
      }
      if (style === 'openai') {
        out.push({
          role: 'assistant',
          // `null` content is only legal beside tool_calls. A turn with neither is a
          // model that answered nothing, and the endpoint refuses the whole request.
          content: entry.text !== '' ? entry.text : calls.length === 0 ? '(no content)' : null,
          ...(calls.length === 0 ? {} : { tool_calls: calls.map((call) => ({ id: call.id, type: 'function', function: { name: call.name, arguments: JSON.stringify(call.input ?? {}) } })) }),
        })
        continue
      }
      const spoken = calls.map((call) => JSON.stringify({ tool: call.name, input: call.input ?? {} })).join('\n')
      out.push({ role: 'assistant', content: [entry.text, spoken].filter((part) => part !== '').join('\n') || '(no content)' })
      continue
    }
    const results = Array.isArray(entry.results) ? entry.results : []
    if (style === 'anthropic') {
      out.push({ role: 'user', content: results.map((result) => ({ type: 'tool_result', tool_use_id: result.id, content: result.text })) })
      continue
    }
    if (style === 'openai') {
      for (const result of results) out.push({ role: 'tool', tool_call_id: result.id, content: result.text })
      continue
    }
    out.push({ role: 'user', content: results.map((result) => `[${result.name} result]\n${result.text}`).join('\n\n') })
  }
  return out
}

/**
 * Fold adjacent same-role messages into one.
 *
 * The Anthropic wire expects alternating turns, and the loop legitimately produces two
 * user messages in a row — the tool results, then the host's own nudge. Merging here
 * means the loop never has to think about it, and no future caller can reintroduce the
 * malformed shape by pushing one more message.
 */
function mergeAdjacent(messages) {
  const out = []
  for (const message of messages) {
    const previous = out[out.length - 1]
    if (previous === undefined || previous.role !== message.role || previous.tool_calls !== undefined) { out.push(message); continue }
    if (Array.isArray(previous.content) && Array.isArray(message.content)) previous.content = [...previous.content, ...message.content]
    else if (typeof previous.content === 'string' && typeof message.content === 'string') previous.content = `${previous.content}\n\n${message.content}`
    else out.push(message)
  }
  return out
}

/** The emulated transport's only addition: the same schemas, described instead of sent. */
const emulatedToolGuide = (tools) => [
  'This model endpoint cannot receive tool definitions, so the same tools are described here.',
  'To call one, reply with exactly one JSON object and nothing else: {"tool":"<name>","input":{...}}',
  'To answer instead, reply with ordinary text and no JSON object.',
  '',
  ...tools.map((tool) => `${tool.name}: ${tool.description}\ninput schema: ${JSON.stringify(tool.schema)}`),
].join('\n')

/**
 * The first number literal in a JSON text that the exact number domain cannot hold, or
 * undefined. The Board holds integers within ±(2^53 − 1) and finite numbers only
 * (exact-or-fail), and a literal beyond that has already lost precision by the time
 * `JSON.parse` returns — 9007199254740993 comes back as 9007199254740992 — so the look
 * happens on the text, before parsing. Strings are skipped: a number inside a string is
 * text, and writing a large identifier as a string is exactly what the teaching asks for.
 */
export function inexactNumberLiteral(text) {
  const s = String(text ?? '')
  const number = /-?\d+(\.\d+)?([eE][+-]?\d+)?/y
  let i = 0
  while (i < s.length) {
    const c = s[i]
    if (c === '"') {
      i += 1
      while (i < s.length && s[i] !== '"') i += s[i] === '\\' ? 2 : 1
      i += 1
      continue
    }
    if (c === '-' || (c >= '0' && c <= '9')) {
      number.lastIndex = i
      const m = number.exec(s)
      if (m === null) { i += 1; continue }
      const literal = m[0]
      i += literal.length
      if (m[1] === undefined && m[2] === undefined) {
        const digits = literal.startsWith('-') ? literal.slice(1) : literal
        if (digits.length >= 16 && BigInt(digits) > 9007199254740991n) return literal
      } else {
        const value = Number(literal)
        if (!Number.isFinite(value) || (Number.isInteger(value) && Math.abs(value) > 9007199254740991)) return literal
        // Underflow is the same disease in the other direction: `1e-400` parses to 0, a
        // value the model never wrote. A mantissa with a non-zero digit that lands on zero
        // is refused too.
        if (value === 0 && /[1-9]/.test(literal.split(/[eE]/)[0])) return literal
      }
      continue
    }
    i += 1
  }
  return undefined
}

/** One JSON object is one call; anything else is an ordinary answer. */
function parseEmulated(text) {
  const trimmed = String(text ?? '').trim()
  const fenced = /^```(?:json)?\s*([\s\S]*?)```$/.exec(trimmed)
  const candidate = fenced === null ? trimmed : fenced[1].trim()
  if (!candidate.startsWith('{')) return { text: trimmed, toolCalls: [] }
  let value
  try { value = JSON.parse(candidate) } catch { return { text: trimmed, toolCalls: [] } }
  if (value === null || typeof value !== 'object' || Array.isArray(value) || typeof value.tool !== 'string') {
    return { text: trimmed, toolCalls: [] }
  }
  const input = value.input !== null && typeof value.input === 'object' && !Array.isArray(value.input) ? value.input : {}
  const inexact = inexactNumberLiteral(candidate)
  return { text: '', toolCalls: [{ id: `emulated_${++emulatedSeq}`, name: value.tool, input, ...(inexact === undefined ? {} : { inexact }) }] }
}

/** Tool arguments that are not a JSON object are refused locally rather than guessed at. */
function parseToolArguments(raw) {
  if (raw === undefined || raw === null) return {}
  if (typeof raw === 'object' && !Array.isArray(raw)) return raw
  // Several OpenAI-compatible endpoints send `""` for a tool with no arguments. That is
  // an empty object, not a malformed call; refusing it would refuse every no-arg verb.
  if (typeof raw === 'string' && raw.trim() === '') return {}
  try {
    const value = JSON.parse(String(raw))
    return value !== null && typeof value === 'object' && !Array.isArray(value) ? value : undefined
  } catch { return undefined }
}

/**
 * One model turn.
 *
 * Returns `{ text, toolCalls }`: prose the user should see, and the calls the model
 * decided to make. Which of the three transports carried it is not visible above this
 * line, and must not be — the loop reasons about tool calls, never about wire shapes.
 */
async function ask(entries, system, { tools = [], cfg = MAIN_CFG } = {}) {
  const wire = openaiStyle(cfg) ? 'openai' : 'anthropic'
  const style = emulatedTools ? 'emulated' : wire
  const declared = !emulatedTools && tools.length > 0
  const systemText = emulatedTools && tools.length > 0 ? `${system}\n\n${emulatedToolGuide(tools)}` : system
  const baseHeaders = { 'content-type': 'application/json' }
  const headers = wire === 'openai'
    ? (cfg.key === '' ? baseHeaders : { ...baseHeaders, authorization: `Bearer ${cfg.key}` })
    : (cfg.key === '' ? baseHeaders : { ...baseHeaders, 'x-api-key': cfg.key, 'anthropic-version': '2023-06-01' })
  const body = wire === 'openai'
    ? {
        model: cfg.model, max_tokens: 6000,
        // Hybrid reasoning models burn the budget on reasoning and answer with empty
        // content unless thinking is turned off; twelve empty rounds is how that shows up.
        ...(process.env.RULITH_MODEL_THINKING === 'enabled' ? { thinking: { type: 'enabled' } } : {}),
        messages: [{ role: 'system', content: systemText }, ...renderMessages(entries, style)],
        ...(declared ? { tools: tools.map((tool) => ({ type: 'function', function: { name: tool.name, description: tool.description, parameters: tool.schema } })) } : {}),
      }
    : {
        model: cfg.model, max_tokens: 6000, system: systemText, messages: mergeAdjacent(renderMessages(entries, style)),
        ...(declared ? { tools: tools.map((tool) => ({ name: tool.name, description: tool.description, input_schema: tool.schema })) } : {}),
      }
  let response
  try {
    response = await fetch(cfg.url, { method: 'POST', headers, body: JSON.stringify(body) })
  } catch (error) {
    // A user-facing tool does not print a raw stack: say who was called and how to change it.
    failTask(`Cannot reach model service ${cfg.url}: ${error?.cause?.code ?? error?.message ?? error}.
   Set RULITH_MODEL_URL for a self-hosted or proxy endpoint. Leave it unset when using the default provider endpoint.`)
    return { text: '', toolCalls: [] }
  }
  const raw = await response.text().catch(() => '')
  let payload
  try { payload = JSON.parse(raw) } catch { payload = {} }
  if (!response.ok) {
    if (response.status === 400 && declared && /tool/i.test(raw)) {
      // The endpoint refuses tool definitions. Describe the identical schemas in the
      // prompt instead of dropping the tools: a model with no tools is not a fallback,
      // it is an agent that can no longer reach the Board.
      emulatedTools = true
      log('The model endpoint refused a request carrying tool definitions. The same six tools are now described in the prompt; their names and schemas are unchanged.')
      return await ask(entries, system, { tools, cfg })
    }
    failTask(`Model service error (${response.status}): ${raw.replace(/\s+/g, ' ').slice(0, 300)}`)
    return { text: '', toolCalls: [] }
  }
  if (emulatedTools) {
    const spoken = wire === 'openai'
      ? String(payload.choices?.[0]?.message?.content ?? '')
      : (Array.isArray(payload.content) ? payload.content : []).filter((block) => block?.type === 'text').map((block) => String(block.text ?? '')).join('\n')
    return parseEmulated(spoken)
  }
  if (wire === 'openai') {
    const message = payload.choices?.[0]?.message ?? {}
    return {
      text: String(message.content ?? ''),
      toolCalls: (Array.isArray(message.tool_calls) ? message.tool_calls : []).map((call, index) => {
        // Chat Completions carries the arguments as JSON *text*, so the exactness look
        // is on that text; a literal beyond the exact domain is refused before parsing.
        const inexact = typeof call.function?.arguments === 'string' ? inexactNumberLiteral(call.function.arguments) : undefined
        return {
          id: String(call.id ?? `call_${index}`),
          name: String(call.function?.name ?? ''),
          input: parseToolArguments(call.function?.arguments),
          ...(inexact === undefined ? {} : { inexact }),
        }
      }),
    }
  }
  // Messages carries `input` as parsed JSON inside the response, so the only place a
  // literal beyond the exact domain is still visible is the response text itself. Provider
  // metadata carries small integers only; a hit is attributed to the calls of this turn.
  const inexact = inexactNumberLiteral(raw)
  const blocks = Array.isArray(payload.content) ? payload.content : []
  return {
    text: blocks.filter((block) => block?.type === 'text').map((block) => String(block.text ?? '')).join('\n'),
    toolCalls: blocks.filter((block) => block?.type === 'tool_use').map((block, index) => ({
      id: String(block.id ?? `call_${index}`),
      name: String(block.name ?? ''),
      input: parseToolArguments(block.input),
      ...(inexact === undefined ? {} : { inexact }),
    })),
  }
}

