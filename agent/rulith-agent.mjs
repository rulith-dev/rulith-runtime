// ── Transcript compaction: rolling window plus segment markers ───────────────
//
// In conversation form `messages` accumulates across segments. A process that runs all
// day and handles dozens of Cases will otherwise grow without bound, and the failure
// shape is a 400 from the model service, not a clean error.
//
// A rolling window rather than summarization: a summary costs another model call on every
// long run and distorts, and a distorted summary has no honest record behind it. The Board
// is the authoritative record — the detail belongs there, not in the transcript. Each
// dropped segment leaves one line, so the model knows work happened and refreshes the
// Board View itself when it needs current state.
//
// The cut must land on a user turn: both provider shapes require the first message to be
// `user`, and cutting between an assistant turn and its tool results is a 400.
const KEEP_MESSAGES = envNumber('RULITH_KEEP_MESSAGES', 24, { min: 2, max: 10_000 })
function compactTranscript(ctx) {
  const messages = ctx.messages
  if (messages.length <= KEEP_MESSAGES) return
  let drop = messages.length - KEEP_MESSAGES
  while (drop < messages.length && messages[drop]?.role !== 'user') drop += 1
  if (drop >= messages.length || drop <= 0) return
  const cut = messages.splice(0, drop)
  const trail = ctx.segmentTrail.length ? ctx.segmentTrail.map((entry, index) => `${index + 1}. ${entry}`).join('\n') : '(none)'
  // The markers are merged into the first user message rather than added as a new one:
  // the role structure is untouched, so no provider shape is deformed by compaction.
  messages[0] = {
    ...messages[0],
    text: `[Transcript compacted] ${cut.length} earlier message(s) were removed. The Board View in the next tool result remains authoritative.
Earlier segments:
${trail}

───
${messages[0].text}`,
  }
  log(`Transcript compacted: dropped ${cut.length}, kept ${messages.length} message(s) and ${ctx.segmentTrail.length} segment marker(s).`)
  emitOn(ctx, 'compact', { dropped: cut.length, kept: messages.length, segments: ctx.segmentTrail.length })
}
