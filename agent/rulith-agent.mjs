/**
 * Report one Board answer to the terminal and to Local.
 *
 * It reports `accepted` and the authority's own teaching, and nothing else. The earlier
 * version also read `receipt.invocation`, `payload.done` and `payload.ok` and printed
 * "completed" or "completed with failure" from them. Those fields are not in Core's
 * published result envelope or Board View — `receipts` is an operator/internal include —
 * so against the real authority they were always absent, every dispatched Action printed
 * the same word, and a guessed shape was standing in for an interface that has not been
 * agreed. Reading a field the authority never promised is how a false "done" gets printed
 * the day the authority starts sending a different one.
 *
 * The Worker-activity gap this leaves is deliberate and visible: see `workerActivityGap`.
 */
function emitVerdict(ctx, name, answer) {
  const result = answer.result ?? {}
  if (answer.handoff !== undefined) {
    // The model asked for one thing and the authority answered with another call's outcome.
    // That is not this call's verdict and it is not silence either: a request the model
    // made did not run, and a person watching must see that as plainly as the model does.
    const from = answer.handoff.tool ?? 'an earlier'
    log(`◎ ${name} was not executed. The authority first handed back the outcome of an earlier ${from} call from this Agent;`
      + ' the model has been given it and decides again.')
    emitOn(ctx, 'handoff', {
      ...(answer.handoff.tool === undefined ? {} : { tool: answer.handoff.tool }),
      ...(answer.handoff.callRef === undefined ? {} : { callRef: answer.handoff.callRef }),
      insteadOf: name,
    })
    return
  }
  if (!BOARD_TOOLS.has(name) && answer.authoritative === true && typeof result.errorCode !== 'string') {
    // A data read, reported as one. It has no `accepted` because it decided nothing: it
    // returned bytes from an object the Board already knows about.
    const size = Number.isFinite(result.totalBytes) ? `${result.totalBytes} byte(s)` : 'an unstated size'
    log(`Data: ${name} returned ${result.complete === true ? 'the final fragment of' : 'a fragment of'} ${size}`
      + `${result.truncated === true ? ', truncated at the read limit' : ''}.`)
    emitOn(ctx, 'artifact-read', {
      cmd: name,
      ...(typeof result.ref === 'string' ? { ref: result.ref } : {}),
      ...(typeof result.mediaType === 'string' ? { mediaType: result.mediaType } : {}),
      complete: result.complete === true,
      truncated: result.truncated === true,
    })
    return
  }
  if (result.accepted === true) {
    emitOn(ctx, 'verdict', { accepted: true, cmd: name })
    log(`Board: ${name} accepted.`)
    if (name === 'ApplyAction') workerActivityGap(ctx)
    return
  }
  const code = String(result.errorCode ?? '')
  const teaching = transportAmbiguous(result) ? transportUnknownTeaching(result) : String(result.teaching ?? (code === '' ? 'The step was rejected.' : code))
  emitOn(ctx, 'verdict', {
    accepted: false, cmd: name, teaching,
    ...(transportAmbiguous(result) ? { transportAmbiguous: true } : {}),
  })
  if (transportAmbiguous(result)) {
    log(`${BOARD_TOOLS.has(name) ? 'Board' : 'Data'} outcome unknown for ${name}: no authoritative receipt was returned.`
      + ' The call keeps its identity at the authority; this host will settle it before anything else runs.')
    // A read whose outcome is unknown is still an unresolved call: it may have been served,
    // and the serial gate is about calls rather than about writes.
  } else log(`${BOARD_TOOLS.has(name) ? 'Board rejected' : 'Data read refused for'} ${name}: ${teaching.slice(0, 240)}`)
}

/**
 * An accepted Action dispatched work whose progress this client cannot yet report.
 *
 * Core has not published where a dispatched invocation's identity appears in the Agent
 * Profile result — receipts are an operator/internal include — so this runtime has no
 * authorised field to read. The honest answer is to say so once per conversation. The
 * alternative, which this replaces, was to read a legacy `receipt.invocation` that the
 * published contract does not contain and let the Worker panel sit empty as though nothing
 * had been dispatched: a false idle is worse than a stated gap, because nobody investigates it.
 */
function workerActivityGap(ctx) {
  if (board.workerGapReported === true) return
  board.workerGapReported = true
  const note = 'An Action was dispatched. This Runtime cannot yet report its invocation identity or progress:'
    + ' the Agent Profile result has no published field carrying it, and Worker receipts are not on this Profile.'
    + ' Follow the Action in Console until that interface is published.'
  log(`◌ ${note}`)
  emitOn(ctx, 'worker-activity-unavailable', { note })
}

/**
 * Execute one model-chosen tool call.
 *
 * What the host owns is attached here and nowhere else: the metadata block and the
 * governance selection that decides which contract a *new* Case runs under. The tool
 * result text handed back is the authority's own JSON, unedited — it already carries the
 * Board View, and a client that summarised it would be teaching the model a picture of
 * the Board rather than the Board.
 */
async function executeToolCall(ctx, call, options) {
  const name = String(call.name ?? '')
  if (!MODEL_TOOLS.includes(name)) {
    const teaching = unknownToolTeaching(name)
    log(`Refused locally: ${teaching.slice(0, 200)}`)
    emitOn(ctx, 'verdict', { accepted: false, cmd: name, teaching, refusedLocally: true })
    return { text: refusal('tool_not_carried', teaching), accepted: false }
  }
  if (call.inexact !== undefined) {
    // Exact-or-fail, at the first membrane the literal crosses. Forwarding the parsed value
    // would send the Board a number the model never wrote, and the Board would then judge
    // (and possibly ground) that other number.
    const teaching = `${name}: the number ${call.inexact} is outside the exact number domain, so nothing was sent.`
      + ' Integers must stay within ±9007199254740991 (2^53-1) and every number must be finite.'
      + ' Pass large identifiers as strings (for example "1234567890123456789"); strings compare by exact text and are never rounded.'
    log(`Refused locally: ${teaching.slice(0, 200)}`)
    emitOn(ctx, 'verdict', { accepted: false, cmd: name, teaching, refusedLocally: true })
    return { text: refusal('bad_command', teaching), accepted: false }
  }
  if (call.input === undefined) {
    const teaching = `${name} arguments were not a JSON object, so nothing was sent. Send arguments matching the tool schema.`
    emitOn(ctx, 'verdict', { accepted: false, cmd: name, teaching, refusedLocally: true })
    return { text: refusal('bad_tool_arguments', teaching), accepted: false }
  }
  const retired = RETIRED_TOOL_FIELDS.filter((field) => Object.hasOwn(call.input, field))
  const hostOwned = HOST_METADATA_FIELDS.filter((field) => Object.hasOwn(call.input, field))
  if (retired.length > 0 || hostOwned.length > 0) {
    const teaching = retired.length > 0 ? retiredFieldTeaching(name, retired) : hostFieldTeaching(name, hostOwned)
    log(`Refused locally: ${teaching.slice(0, 200)}`)
    emitOn(ctx, 'verdict', { accepted: false, cmd: name, teaching, refusedLocally: true })
    return { text: refusal(retired.length > 0 ? 'retired_wire_field' : 'host_owned_field', teaching), accepted: false }
  }
  let input = { ...call.input }
  let openedCaseType
  if (name === 'OpenCase') {
    // Two public shapes: {caseType, businessKey?} creates, {caseId} focuses or resumes.
    // A mixed form is the authority's to reject, and it is left intact so that the model
    // is told which rule it broke rather than having one half silently removed.
    const focusForm = typeof input.caseId === 'string' && input.caseId.trim() !== ''
    if (!focusForm) {
      // Governance selection is the operator's, not the model's: when a Case Type is
      // pinned on the command line or in the environment, that is the contract the Case
      // opens under. With nothing pinned the model may choose from its Agent's catalogue
      // and the host only supplies the default.
      const asked = typeof input.caseType === 'string' && input.caseType.trim() !== '' ? input.caseType.trim() : ''
      openedCaseType = options.caseTypePinned || asked === '' ? options.caseType : asked
      input = {
        ...input,
        caseType: openedCaseType,
        ...(options.businessKey === undefined ? {} : { businessKey: options.businessKey }),
      }
    }
  }
  const before = new Set(board.roots.map((row) => row.caseId))
  const answer = await callTool(ctx, name, input)
  // A refusal the host already announced is not announced again as though the Board had spoken.
  if (answer.refusedLocally !== true) emitVerdict(ctx, name, answer)
  const accepted = answer.result?.accepted === true
  if (name === 'OpenCase' && accepted) {
    for (const row of board.roots) {
      if (before.has(row.caseId)) continue
      if (openedCaseType !== undefined) row.caseType = openedCaseType
      log(`\nCase Context in focus: "${row.caseId}" · acceptance root "${row.root}" on Agent Board "${agentId}".`)
      emitOn(ctx, 'case-open', { caseId: row.caseId, root: row.root, caseType: row.caseType ?? '', ok: true })
      ctx.detachedCase = undefined
    }
  }
  const closed = [...before].filter((caseId) => !board.roots.some((row) => row.caseId === caseId))
  return {
    text: answer.text,
    accepted,
    view: answer.view,
    // The call reached the wire and its outcome is not known. Everything downstream —
    // the rest of this turn's queue, the next model turn — stops until it is settled.
    unresolved: answer.refusedLocally !== true && answer.authoritative !== true,
    // The request did not run, and what came back belongs to an earlier call. The rest of
    // the turn was chosen before the model knew that, so it stops here too: carrying on
    // would execute proposals made against a Board the model has just been told it was
    // wrong about — and would do it without the model having seen the outcome.
    handedOver: answer.handoff !== undefined,
    closed: name === 'CloseCase' && accepted && closed.length > 0,
    disposition: String(input.disposition ?? ''),
  }
}

/**
 * Add one existing Case to this conversation's focus.
 *
 * This is the operator's choice, reached through `--case` and the Local UI, and it is the
 * same public tool the model calls: `OpenCase({caseId})` is a focus, and for a paused Case
 * a resume. There is no private lifecycle route left, and the runtime does not read the
 * Board first to decide whether the Case is running or paused — that decision, and the
 * policy behind it, belongs to the authority.
 */
async function focusExistingCase(ctx, caseId) {
  const answer = await callTool(ctx, 'OpenCase', { caseId })
  if (answer.result?.accepted === true) {
    const row = board.roots.find((entry) => entry.caseId === caseId)
    log(`◎ Case "${caseId}" is in focus for this conversation${row === undefined ? '' : ` (acceptance root "${row.root}", ${row.status})`}.`)
    return { ok: true }
  }
  if (answer.handoff !== undefined) {
    // The focus request never ran: the authority answered it by handing back an earlier
    // call's outcome, which is what §5.2 says the first new request gets. Two things must
    // not happen here. The Case is not in focus, so nothing may say it is; and the earlier
    // outcome belongs to the model, so it is carried out of this function rather than
    // dropped on the floor. The focus request is not re-sent either — the model decides
    // what to do next, with the outcome in hand.
    const from = answer.handoff.tool ?? 'an earlier'
    log(`◎ Case "${caseId}" was not brought into focus: the authority first handed back the outcome of an earlier ${from}`
      + ' call from this Agent. Nothing was focused, and nothing was re-sent.')
    return { ok: false, handedOver: true, tool: answer.handoff.tool, handoffText: answer.handoffText,
      teaching: `The request that would have focused it did not run; the authority delivered an earlier ${from} call's outcome instead.` }
  }
  const teaching = transportAmbiguous(answer.result)
    ? transportUnknownTeaching(answer.result)
    : String(answer.result?.teaching ?? answer.result?.errorCode ?? 'the authority refused the focus request')
  log(`✗ Case "${caseId}" could not be brought into focus: ${teaching.slice(0, 240)}`)
  // A host feature is not an exemption from the gate. `--case` and the Local UI reach the
  // same public tool over the same connection, so a focus request whose outcome is unknown
  // holds the Agent exactly as a model-chosen call would: the caller must settle it before
  // the model is asked anything.
  return { ok: false, teaching, unresolved: answer.authoritative !== true && answer.refusedLocally !== true }
}

/**
 * One turn of work: a user message, or one autopilot task.
 *
 * `policy: 'return'` hands control back as soon as the model answers with text.
 * `policy: 'continue'` keeps going while the Board still has something to say — but the
 * continuation condition is never "the model did not say DONE". It is the authority's own
 * lifecycle: a focused root that is still running, an explicit close, or the round budget.
 *
 * Returns `{ note, outcome, caseId, activeCaseId, activeCaseIds, pendingCaseId, opened }`.
 * `opened` is the machine-readable half of `note`: callers used to have to read prose to
 * tell "the Case ran and did not finish" from "no Case ever existed", and the one-shot CLI
 * did not read it at all — it exited 0 for a task that never started.
 */
async function runCaseTurn(ctx, userText, {
  policy = 'return',
  caseType = selectedCaseType,
  caseTypePinnedForTurn = caseTypePinned,
  businessKey = selectedBusinessKey,
  requestedCaseId = '',
} = {}) {
  compactTranscript(ctx)
  const messages = ctx.messages
  let opened = board.roots.length > 0
  let note = ''
  let outcome = 'pending'
  let nudged = false
  let selectionNotice = ''
  let lastCaseId = board.roots[0]?.caseId ?? null
  const detachedPendingCaseId = ctx.detachedCase?.caseId ?? null
  const configuredResume = resumeCase
  resumeCase = '' // Resume applies to the first segment only.
  const explicitResume = requestedCaseId || configuredResume
  /** Host-recovery notes to put in front of the model before it is asked anything. */
  const carried = []

  // Settle first, ask later. An unresolved call from an earlier turn — or from an earlier
  // process, or from the client this connection replaced — is the authority's to close out,
  // and until it is closed out this Agent may not read the Board, write to it, or take a
  // model turn. Doing this before the focus request below is deliberate: `--case` and the
  // Local UI reach the same public tool, and a host feature is not an exemption.
  /** Stop the turn without asking the model, and say why. */
  const blockedTurn = (settled) => {
    log(`\n⚠ ${settled.teaching}`)
    emitOn(ctx, 'blocked', { reason: settled.state, teaching: settled.teaching })
    ctx.segmentTrail.push(`[blocked · ${settled.state}] ${userText.slice(0, 60)}`)
    const heldCaseIds = board.roots.map((row) => row.caseId)
    return {
      note: settled.teaching, outcome: 'blocked', caseId: heldCaseIds[0] ?? lastCaseId,
      activeCaseId: heldCaseIds[0] ?? null, activeCaseIds: heldCaseIds,
      pendingCaseId: heldCaseIds[0] ?? detachedPendingCaseId, opened,
    }
  }

  {
    const settled = await settleRecovery(ctx)
    if (!settled.ok) return blockedTurn(settled)
    if (settled.note !== undefined) carried.push(settled.note)
  }

  // Bringing a Case into focus is a host feature, reached through `--case` and the Local
  // UI. Which Cases this conversation is on is not a decision a model turn may make on
  // the operator's behalf, and focus is additive: a session may hold several roots.
  if (explicitResume !== '') {
    if (board.roots.some((row) => row.caseId === explicitResume)) {
      selectionNotice = `Rulith Case ${JSON.stringify(explicitResume)} is already in this conversation's focus.`
    } else {
      const focused = await focusExistingCase(ctx, explicitResume)
      if (focused.ok) {
        opened = true
        lastCaseId = explicitResume
        ctx.detachedCase = undefined
      } else if (focused.handedOver) {
        // The outcome the authority delivered instead is the model's to judge, in the same
        // labelled host-recovery form a mechanical claim would have produced.
        carried.push(handoffNote(focused.tool, focused.handoffText ?? '(the outcome was not readable)'))
        emitOn(ctx, 'handoff', { ...(focused.tool === undefined ? {} : { tool: focused.tool }), insteadOf: 'OpenCase' })
        selectionNotice = `The requested existing Rulith Case ${JSON.stringify(explicitResume)} was not brought into focus:`
          + ` ${focused.teaching} Do not claim that Case is active.`
      } else if (focused.unresolved) {
        // The focus request reached the wire and its outcome is unknown. It is a Board call
        // like any other, so the Agent is now held: settle it before the model is asked, and
        // stop the turn if it cannot be settled.
        const settled = await settleRecovery(ctx, { force: true })
        if (!settled.ok) return blockedTurn(settled)
        if (settled.note !== undefined) carried.push(settled.note)
        selectionNotice = `The requested existing Rulith Case ${JSON.stringify(explicitResume)} could not be brought into focus:`
          + ` ${focused.teaching.slice(0, 200)} Answer the user normally; do not claim that Case is active.`
      } else {
        selectionNotice = `The requested existing Rulith Case ${JSON.stringify(explicitResume)} could not be brought into focus:`
          + ` ${focused.teaching.slice(0, 200)} Answer the user normally; do not claim that Case is active.`
      }
    }
  }

  // A recovered outcome goes in ahead of the user's message and in its own turn: it is the
  // answer to something the model asked earlier, not part of what the user just said.
  for (const note of carried.splice(0)) messages.push(userEntry(note))

  messages.push(userEntry([
    `${policy === 'continue' ? 'Task' : 'User message'}: ${userText}`,
    selectionNotice === '' ? '' : `\n\n${selectionNotice}`,
    board.roots.length === 0 ? '' : `\n\nCases in focus: ${board.roots.map((row) => `${row.caseId} (root ${row.root}, ${row.status})`).join(' · ')}`,
    board.lastView === undefined ? '' : `\n\nBoard View last observed (not refreshed; call QueryBoard for a current one):\n${viewText(board.lastView)}`,
  ].join('')))

  for (let round = 1; round <= MAX_ROUNDS; round++) {
    emitOn(ctx, 'round', { n: round, ...(policy === 'return' ? { conversational: true } : {}) })
    // The round number also reaches the terminal: it used to travel only in the event
    // stream, so any instrument counting rounds from stdout read zero forever.
    if (policy === 'continue') log(`— Round ${round} —`)
    // An interjection does not interrupt: what the local operator says while a segment is
    // running joins this round. Only the default slot has this line — stdin belongs to
    // that one operator, not to a remote client's conversation.
    const interject = policy === 'continue' && ctx === defaultSlot ? pollInterject?.() : undefined
    if (interject) {
      log(`\n[User interjection] ${interject}`)
      emitOn(ctx, 'user', { text: interject, interject: true })
      messages.push(userEntry(`[User] ${interject}`))
    }

    // Anything recovered since the last round is put in front of the model before it is
    // asked again — it is the outcome of a step this conversation already proposed.
    for (const note of carried.splice(0)) messages.push(userEntry(note))
    const reply = await ask(messages, systemFor(ctx), { tools: modelTools })
    const say = String(reply.text ?? '').trim()
    if (say !== '') log(`\n${say.slice(0, 1200)}`)
    messages.push(assistantEntry(reply.text, reply.toolCalls))
    emitOn(ctx, 'propose', {
      say,
      ...(reply.toolCalls.length === 0 ? {} : {
        cmd: reply.toolCalls.map((call) => String(call.name ?? '')).join('+'),
        tool: { action: String(reply.toolCalls[0].name ?? '') },
      }),
    })

    if (reply.toolCalls.length === 0) {
      // A plain answer is a complete conversational turn. Focused Cases are deliberately
      // left exactly as they are; the next user message may continue one, ask about it,
      // or ignore it. The host never continues merely because work is unfinished.
      if (policy === 'return') {
        outcome = 'conversation'
        note = board.roots.length === 0
          ? 'Response delivered without opening a Rulith Case.'
          : `Response delivered; Rulith Case(s) ${board.roots.map((row) => `"${row.caseId}"`).join(', ')} remain in focus.`
        break
      }
      if (board.roots.length === 0) { outcome = 'no-case'; note = 'Response only; no Case was opened on the Board.'; break }
      const live = liveRootsOf(ctx)
      if (live.length === 0) {
        outcome = 'completed'
        note = `No focused Case is still running (${board.roots.map((row) => `${row.caseId}=${row.status}`).join(' · ')}).`
        break
      }
      if (nudged) {
        note = `The model stopped while ${live.map((row) => `"${row.caseId}"`).join(', ')} ${live.length === 1 ? 'is' : 'are'} still running on the Board.`
        break
      }
      // One nudge, once — never an unbounded retry. The judgement is the Board's, not a
      // guess about the prose: it is the lifecycle that says the work is not finished.
      nudged = true
      messages.push(userEntry(`These Cases are still running on the Board: ${live.map((row) => `${row.caseId} (root ${row.root})`).join(' · ')}.\n`
        + `Board View last observed:\n${viewText(board.lastView)}\n\nTake the next step, read the current view with QueryBoard,`
        + ' or close a Case with a disposition that says why it cannot be finished.'))
      continue
    }

    // Several calls in one model turn are executed **one after another**, each completing
    // before the next is sent — that is what serial means, and it is not the same as
    // dropping all but the first. Dropping them looked serial from the wire and was a
    // quiet loss: the model had proposed work this host silently declined to carry, and
    // the model's own re-reading of the Board View was the only thing that ever recovered
    // it. Each result is fed back in order, so a later call is judged by the authority
    // against the closure the earlier one produced.
    //
    // The queue suspends — it does not continue and does not discard — the moment one call
    // ends unresolved. From that point nothing may be sent for this Agent at all, so the
    // remaining calls are answered as not executed and the recovery gate takes over.
    const results = []
    let closedDisposition
    // A tool result may itself have announced that something is outstanding — a Worker
    // receipt that arrived between calls, a takeover. Sending the next queued call anyway
    // would be this host ignoring an answer it has already read.
    let suspended = connection.recovery !== undefined && connection.recovery.state !== 'none'
    let notSent = 0
    for (const call of reply.toolCalls) {
      if (suspended) {
        notSent += 1
        // Every tool_use still receives a tool_result: an unanswered one is a malformed
        // conversation on the Anthropic wire.
        results.push({
          id: call.id,
          name: String(call.name ?? ''),
          text: refusal('call_queue_suspended', 'This call was not sent. An earlier call in the same turn did not resolve —'
            + ' its outcome is unknown, or the authority answered it by handing back an earlier result instead of'
            + ' running it. While that is true this Agent sends nothing further: no write, no query, no artifact read.'
            + ' Read what you were given, then decide again; nothing has been carried out on your behalf.'),
        })
        continue
      }
      const executed = await executeToolCall(ctx, call, { caseType, caseTypePinned: caseTypePinnedForTurn, businessKey })
      results.push({ id: call.id, name: String(call.name ?? ''), text: executed.text })
      if (board.roots.length > 0) { opened = true; lastCaseId = board.roots[0].caseId }
      if (executed.closed) closedDisposition = executed.disposition === '' ? 'completed' : executed.disposition
      if (executed.unresolved || executed.handedOver
        || (connection.recovery !== undefined && connection.recovery.state !== 'none')) suspended = true
    }
    messages.push(resultsEntry(results))

    if (suspended) {
      if (notSent > 0) {
        log(`◌ ${notSent} further call(s) proposed in this turn were not sent: an earlier call in it did not resolve,`
          + ' and nothing further goes out for this Agent until that is settled.')
        emitOn(ctx, 'queue-suspended', { notSent })
      }
      // Forced: this host just lost track of a call's outcome, so what it last knew about
      // the recovery state is exactly the knowledge that is now stale.
      const settled = await settleRecovery(ctx, { force: true })
      if (!settled.ok) {
        log(`\n⚠ ${settled.teaching}`)
        emitOn(ctx, 'blocked', { reason: settled.state, teaching: settled.teaching })
        outcome = 'blocked'
        note = settled.teaching
        break
      }
      if (settled.note !== undefined) carried.push(settled.note)
    }

    if (policy !== 'continue') continue
    if (closedDisposition !== undefined && liveRootsOf(ctx).length === 0) {
      outcome = VOID_DISPOSITIONS.has(closedDisposition) ? 'void' : 'completed'
      note = VOID_DISPOSITIONS.has(closedDisposition)
        ? `The Case was closed as ${closedDisposition}.`
        : 'The Board accepted closure and the Case is completed.'
      break
    }
  }

  if (note === '') note = `Stopped at the ${MAX_ROUNDS}-round limit.`
  if (policy === 'continue') {
    // The shadow persona (`--shadow`): an adversarial review at the end of a segment. It
    // may only assert dissenting facts; its teeth are on the Board (a confirmed defect
    // blocks certification), not in a branch of this process.
    // The shadow reviewer writes to the Board, so it is behind the same gate as everything
    // else. Running it after the turn was blocked would be this host announcing that no
    // further call would be sent and then sending one.
    if (withShadow && board.roots.length > 0 && outcome !== 'blocked' && board.unresolved === undefined) {
      await shadowReview(ctx, userText)
    }
    if (note === `Stopped at the ${MAX_ROUNDS}-round limit.`) {
      log(`\n⚠ ${note} Increase RULITH_MAX_ROUNDS only after reviewing why the workflow did not converge.`)
    }
  }
  const activeCaseIds = board.roots.map((row) => row.caseId)
  const activeCaseId = activeCaseIds[0] ?? null
  const pendingCaseId = policy === 'continue' ? (liveRootsOf(ctx)[0]?.caseId ?? null) : detachedPendingCaseId
  if (policy === 'continue' && activeCaseId !== null) {
    log(`\nCase(s) ${activeCaseIds.map((id) => `"${id}"`).join(', ')} remain in focus: ${note}\n`
      + '   Stopping is not completion. Resume with --case <id>, or resolve them in Console.')
    emitOn(ctx, 'case-pending', { caseId: activeCaseId, activeCaseIds, reason: note, note })
  }
  ctx.segmentTrail.push(`[${policy === 'continue' ? 'case' : 'conversation'}${activeCaseId === null ? '' : ` · case ${activeCaseId} in focus`}] ${userText.slice(0, 60)}${userText.length > 60 ? '…' : ''} → ${note}`)
  if (ctx.segmentTrail.length > 40) ctx.segmentTrail.splice(0, ctx.segmentTrail.length - 40)
  return { note, outcome, caseId: activeCaseId ?? lastCaseId, activeCaseId, activeCaseIds, pendingCaseId, opened }
}

/** Shadow review: an adversarial reading of the last observed Board View and this
 *  segment's history, looking only for real defects. A finding is asserted on the Board
 *  as `shadow_finding`; the shadow may never edit anything the primary persona wrote.
 *
 *  It reads the view this conversation already observed rather than fetching a fresh one:
 *  the review is of what this segment actually did, and a freshly-read view would describe
 *  a Board that has moved on. The finding it writes is judged by the authority against the
 *  premises in force when the write executes, as every other write is. */
async function shadowReview(ctx, userText) {
  const verdict = await ask(
    [userEntry(`Completed segment: ${userText}\n\nBoard View last observed:\n${viewText(board.lastView)}`)],
    `You are the Agent's adversarial shadow reviewer. Assume the primary Agent may be wrong and identify only concrete defects:
- Is every conclusion actually supported? Are values abnormal, sources doubtful, or expected materials missing?
- Did claims that require verification go through a trusted computation or source, or were they merely stated?
- Is unfinished work being presented as complete?
Do not invent criticism. If no issue is substantiated, reply with exactly PASS.
Otherwise return at most three lines, each formatted FINDING: <one precise issue with a node or value>.`,
    { cfg: SHADOW_CFG },
  )
  const findings = String(verdict.text ?? '').split('\n').map((line) => line.trim()).filter((line) => line.startsWith('FINDING:')).slice(0, 3)
  if (findings.length === 0) { log('◆ Shadow review: PASS'); emitOn(ctx, 'shadow', { pass: true }); return true }
  for (const finding of findings) log(`◆ Shadow review: ${finding.slice(0, 200)}`)
  emitOn(ctx, 'shadow', { pass: false, findings })
  const operations = findings.map((finding, index) => ({
    op: 'assert_fact', id: `SF_${Date.now().toString(36)}_${index}`,
    predicate: 'shadow_finding', args: { text: finding.slice(9, 240).trim() },
  }))
  const answer = await callTool(ctx, 'ApplyBatch', { operations })
  if (answer.handoff !== undefined) {
    // Not written, and not rejected either: the write never ran, because the authority
    // answered it with an earlier call's outcome. Reporting either of the other two would
    // leave a reader believing a finding is on the Board when it is not.
    log(`◆ The shadow finding was not written: the authority handed back the outcome of an earlier`
      + ` ${answer.handoff.tool ?? 'call'} instead. The finding is not on the Board.`)
    emitOn(ctx, 'shadow-not-written', { ...(answer.handoff.tool === undefined ? {} : { tool: answer.handoff.tool }) })
    return false
  }
  if (answer.result?.accepted !== true) log(`◆ Board rejected the shadow finding: ${String(answer.result?.teaching ?? '').slice(0, 120)}`)
  return false
}

if (SERVE) {
  // ── The intake loop: accept over loopback, run per slot, keep a bounded ledger ──
  //
  // This is the minimal unattended shape a web backend can embed: it reads no stdin and
  // opens no window, it just puts `runCaseTurn` behind one HTTP port. Nothing below the
  // scheduler changes — intake only queues, routes and records.
  //
  // **One segment at a time, for the whole Agent.** Each conversation keeps its own FIFO so
  // that two clients' messages are never woven into one transcript, but the queues are
  // drained one segment at a time, because this Agent has one authenticated connection and
  // its Board calls are serial.
  //
  // The retired alternative — a session per conversation, several segments at once — was
  // not concurrency, it was a fight: the second conversation's `initialize` took the Agent
  // over, and the first conversation's next call came back `connection_replaced`. Anyone
  // who needs genuine parallelism needs another Agent, which means another process with
  // another token.
  const runs = []       // ring buffer: the most recent SERVE_RUNS_MAX records
  /** The one segment running now, or nothing. The Agent has one turn in flight at a time. */
  let inFlight
  const pushRun = (r) => { runs.push(r); while (runs.length > SERVE_RUNS_MAX) runs.shift() }
  let acceptingTasks = true

  // Conversation slots isolate local transcripts and queues, and nothing else. The
  // connection, the focus and the Board View belong to the Agent; a slot cannot hold a
  // Case of its own, and it cannot take the connection away from another slot.
  const sessions = new Map()
  const detachedCases = new Map()
  const rememberDetachedCase = (session, recovery) => {
    detachedCases.delete(session)
    detachedCases.set(session, recovery)
    while (detachedCases.size > SERVE_SLOTS_MAX) detachedCases.delete(detachedCases.keys().next().value)
  }
  const detachIdleCase = (session, slot) => {
    const recovery = board.roots.length === 0 ? slot.detachedCase : {
      caseId: board.roots[0].caseId, root: board.roots[0].root, detachedAt: Date.now(),
    }
    if (recovery === undefined) return
    rememberDetachedCase(session, recovery)
    // A recovery hint that was already detached is merely moving between bounded maps.
    // Emit the public recovery record once, when focused Cases first leave their slot.
    if (board.roots.length === 0) return
    const caseId = recovery.caseId
    const at = Date.now()
    const note = `Conversation "${session}" was reclaimed at the local session limit. Rulith Case "${caseId}" remains unchanged on the Board and may be selected explicitly later.`
    const rec = {
      id: `detached-${randomUUID()}`, text: '(conversation reclaimed)', at,
      startedAt: at, endedAt: at, note, board: agentId, sessionKey: session,
      caseId, pendingCaseId: caseId, console: consoleUrl,
    }
    pushRun(rec)
    emit('session-detached', { session, caseId, pendingCaseId: caseId, note, board: agentId, console: consoleUrl })
    log(`◎ ${note}`)
  }
  const evictIfNeeded = () => {
    while (sessions.size >= SERVE_SLOTS_MAX) {
      let victim
      for (const [k, s] of sessions) {
        if (!s.busy && s.queue.length === 0) { victim = k; break }
      }
      if (victim === undefined) {
        log(`All ${SERVE_SLOTS_MAX} conversation slots have queued work. Refusing a new conversation rather than interrupting an Agent turn.`)
        return false
      }
      const slot = sessions.get(victim)
      detachIdleCase(victim, slot)
      sessions.delete(victim)
      if (board.roots.length === 0) log(`Evicted least-recently-used idle conversation "${victim}" at the ${SERVE_SLOTS_MAX}-conversation limit. This Agent has no focused Rulith Case.`)
      emit('slot-evicted', { session: victim, slots: sessions.size })
    }
    return true
  }
  const slotFor = (sessionKey) => {
    if (sessionKey === '') return defaultSlot
    const hit = sessions.get(sessionKey)
    if (hit !== undefined) {
      sessions.delete(sessionKey); sessions.set(sessionKey, hit) // LRU: a hit moves to the tail
      hit.lastUsed = Date.now()
      return hit
    }
    if (!evictIfNeeded()) return undefined
    const slot = makeSlot(sessionKey)
    const recovery = detachedCases.get(sessionKey)
    if (recovery !== undefined) {
      detachedCases.delete(sessionKey)
      slot.detachedCase = recovery
    }
    sessions.set(sessionKey, slot)
    log(`Opened session "${sessionKey}" (${sessions.size}/${SERVE_SLOTS_MAX} slots).`)
    emit('slot-open', { session: sessionKey, slots: sessions.size })
    return slot
  }

  // The local service uses a random key, a loopback Host/Origin gate, and a 64KB JSON body cap.
  const serveGate = (req) => {
    const url = new URL(req.url, 'http://127.0.0.1')
    const key = req.headers['x-rulith-serve'] ?? url.searchParams.get('k') ?? ''
    if (key !== SERVE_KEY) return 'Missing or invalid task key. Use the startup key in the x-rulith-serve header, or ?k= for SSE.'
    const origin = req.headers.origin
    if (origin !== undefined && !/^https?:\/\/(127\.0\.0\.1|localhost)(:\d+)?$/.test(origin)) return `Cross-origin request rejected (Origin: ${origin}). The task endpoint accepts local origins only.`
    const host = String(req.headers.host ?? '')
    if (!/^(127\.0\.0\.1|localhost)(:\d+)?$/.test(host)) return `Non-local Host rejected (${host}) to prevent DNS rebinding.`
    return null
  }
  /** Every slot (default first, session slots in LRU order): queueing, scheduling and
   *  snapshots all read this one view. */
  const allSlots = () => [defaultSlot, ...sessions.values()]
  const snapshot = () => ({
    ok: true, agentId, url: URL_BASE,
    concurrency: 1,
    slotsMax: SERVE_SLOTS_MAX, sessions: sessions.size,
    // `running` is a single record or null — the shape existing callers and the
    // regression net read. With concurrency it is the earliest still running; everything
    // running is in `runningAll`. Changing the old field's meaning would change a
    // contract quietly.
    running: inFlight ?? null,
    runningAll: inFlight === undefined ? [] : [inFlight],
    queued: allSlots().flatMap((s) => s.queue.map((q) => ({ id: q.id, text: q.text, at: q.at, ...(s.key === '' ? {} : { sessionKey: s.key }) }))),
    runs: runs.slice(-SERVE_RUNS_MAX),
  })
  const terminalizeQueuedTasks = (reason) => {
    for (const slot of allSlots()) {
      for (const item of slot.queue.splice(0)) {
        const rec = {
          id: item.id, text: item.text, at: item.at,
          startedAt: item.at, endedAt: Date.now(),
          note: `Task never started: ${reason}`,
          board: agentId,
          ...(slot.key === '' ? {} : { sessionKey: slot.key }),
          ...(board.roots.length === 0 ? {} : { console: consoleUrl }),
        }
        pushRun(rec)
        emit('task-done', rec)
        log(`✗ ${rec.note} (task ${item.id})`)
      }
    }
  }

  const serveSrv = http.createServer((req, res) => {
    const deny = (why, status = 403) => {
      res.writeHead(status, { 'content-type': 'application/json; charset=utf-8' })
      res.end(JSON.stringify({ ok: false, teaching: why }))
    }
    const path = (req.url ?? '/').split('?')[0]
    if (req.method === 'POST' && path === '/task') {
      const bad = serveGate(req)
      if (bad !== null) return deny(bad)
      if (!acceptingTasks) return deny('The Agent credential was rejected. Rotate it in Console and restart Rulith Local.', 503)
      const ct = String(req.headers['content-type'] ?? '')
      if (!ct.startsWith('application/json')) return deny('Only application/json is accepted; plain-text bodies can bypass browser preflight checks.')
      // Collected as bytes and decoded once: concatenating chunks as strings splits
      // multi-byte characters across chunk boundaries.
      const bodyChunks = []
      let size = 0
      let over = false
      req.on('data', (c) => { size += c.length; if (size > LOCAL_REQUEST_MAX_BODY) { over = true; req.destroy(); return } bodyChunks.push(c) })
      req.on('end', () => {
        if (over) return deny('Request body exceeds 64KB.')
        const raw = Buffer.concat(bodyChunks).toString('utf8')
        let text = ''
        let sessionKey = ''
        let requestedCaseId = ''
        let requestedCaseIdValue
        let caseType = selectedCaseType
        // A caller that names a Case Type has made the governance selection for this task,
        // exactly as `--case-type` does for the process. The model may not move off it.
        let caseTypeGiven = caseTypePinned
        let businessKey = selectedBusinessKey
        try {
          const b = JSON.parse(raw || '{}')
          text = String(b.text ?? '').trim()
          sessionKey = String(b.sessionKey ?? '').trim()
          requestedCaseIdValue = b.caseId
          caseTypeGiven = caseTypeGiven || (typeof b.caseType === 'string' && b.caseType.trim() !== '')
          caseType = String(b.caseType ?? selectedCaseType).trim()
          businessKey = b.businessKey ?? selectedBusinessKey
        } catch { return deny('Body is not valid JSON. Expected {"text":"...","caseType":"exploration","businessKey":{"id":"..."},"sessionKey":"optional","caseId":"optional-existing-case"}.') }
        if (text === '') return deny('Missing text. Expected {"text":"process this task","caseType":"exploration"}.', 400)
        if (requestedCaseIdValue !== undefined && typeof requestedCaseIdValue !== 'string') return deny('caseId must be a string copied exactly from /runs or Console.', 400)
        requestedCaseId = String(requestedCaseIdValue ?? '').trim()
        if (!/^[a-z][a-z0-9_-]{1,63}$/.test(caseType)) return deny('caseType must be a 2-64 character lowercase identifier from the Agent Case Type catalog.', 400)
        if (businessKey !== undefined && (businessKey === null || typeof businessKey !== 'object' || Array.isArray(businessKey)
          || Object.keys(businessKey).length === 0 || !Object.values(businessKey).every((v) => typeof v === 'string'
            || typeof v === 'boolean' || (typeof v === 'number' && Number.isFinite(v))))) {
          return deny('businessKey must be a non-empty JSON object whose keys match the selected Case Contract and whose values are finite JSON scalars.', 400)
        }
        // Missing keys start independent conversations. The caller receives the generated
        // key and must echo it on follow-ups; unrelated clients never share a default Case.
        if (sessionKey === '') sessionKey = `ctx-${Date.now().toString(36)}-${randomUUID().slice(0, 8)}`
        // Session keys select bounded local transcript/queue slots and their authenticated
        // MCP session. They never select a Board.
        if (sessionKey.length > SESSION_KEY_MAX) {
          return deny(`sessionKey exceeds ${SESSION_KEY_MAX} characters (${sessionKey.length} received). It cannot be truncated because it identifies a local conversation slot. Use a short opaque identifier.`, 400)
        }
        if (requestedCaseId.length > 256) return deny('caseId exceeds 256 characters. Use the exact Case ID returned by /runs or shown in Console.', 400)
        const slot = slotFor(sessionKey)
        if (slot === undefined) return deny(`Conversation capacity is full (${SERVE_SLOTS_MAX} slots), and every slot is busy. Retry later or continue an existing sessionKey.`, 429)
        const item = { id: nextTaskId(), text, caseType, caseTypePinned: caseTypeGiven, businessKey, caseId: requestedCaseId, at: Date.now(), sessionKey }
        slot.queue.push(item)
        slot.lastUsed = item.at
        const depth = allSlots().reduce((n, s) => n + s.queue.length, 0)
        emit('task-queued', { id: item.id, text: item.text, depth, session: sessionKey })
        res.writeHead(202, { 'content-type': 'application/json; charset=utf-8' })
        res.end(JSON.stringify({ ok: true, id: item.id, queued: depth, sessionKey,
          teaching: 'Queued. Read GET /runs?k=<key>, or add &stream=1 for SSE.' }))
        pump()
      })
      return
    }
    if (path === '/runs') {
      const bad = serveGate(req)
      if (bad !== null) return deny(bad)
      const wantsStream = new URL(req.url, 'http://127.0.0.1').searchParams.get('stream') === '1'
        || String(req.headers.accept ?? '').includes('text/event-stream')
      if (!wantsStream) {
        res.writeHead(200, { 'content-type': 'application/json; charset=utf-8' })
        return void res.end(JSON.stringify(snapshot()))
      }
      // Standalone automation may observe the same bounded event stream that Local receives over IPC.
      res.writeHead(200, { 'content-type': 'text/event-stream', 'cache-control': 'no-cache', connection: 'keep-alive' })
      for (const ev of events) res.write(`data: ${JSON.stringify(ev)}\n\n`)
      clients.add(res)
      req.on('close', () => clients.delete(res))
      return
    }
    return deny('Available endpoints: POST /task {"text":"...","caseType":"exploration","businessKey":{"id":"..."},"sessionKey":"optional","caseId":"optional-existing-case"} and GET /runs?k=<key> (add &stream=1 for SSE).', 404)
  })
  await new Promise((r) => serveSrv.listen(SERVE_PORT, '127.0.0.1', r))
  log(`
Task endpoint ready (one Agent, one connection, one segment at a time · ${SERVE_SLOTS_MAX} conversation limit): http://127.0.0.1:${SERVE_PORT}
  Submit: curl -s -XPOST http://127.0.0.1:${SERVE_PORT}/task -H 'content-type: application/json' -H 'x-rulith-serve: ${SERVE_KEY}' -d '{"text":"…","caseType":"exploration"}'
  Contracted Case Types also send businessKey with the exact Case Contract argument names.
  Continue a conversation by echoing the sessionKey returned by the first request: -d '{"text":"…","sessionKey":"conversation-1"}'
  Bring an existing running or paused Case into a conversation's focus: add "caseId":"<id>" from /runs or Console.
  Messages are ordinary conversation. The Agent opens or advances a Rulith Case only when it calls one of the Board tools.
  Inspect: curl -s 'http://127.0.0.1:${SERVE_PORT}/runs?k=${SERVE_KEY}'
  The key is randomized on every start. Loopback alone is not an authorization boundary.`)
  emit('start', { agentId, url: URL_BASE, task: '(task endpoint)', concurrency: 1 })

  /** Handle one item at the head of one conversation's queue. There is one of these
   *  running at a time for the whole Agent: `slot.busy` orders one conversation's own
   *  messages, and `inFlight` is the Agent-wide gate. */
  async function runOne(slot) {
    const item = slot.queue.shift()
    if (item === undefined) return
    slot.busy = true
    slot.lastUsed = Date.now()
    slot.taskId = item.id
    const flight = { id: item.id, text: item.text, startedAt: Date.now(),
      ...(slot.key === '' ? {} : { sessionKey: slot.key }) }
    inFlight = flight
    emit('task-start', { id: item.id, text: item.text,
      ...(slot.key === '' ? {} : { session: slot.key }) })
    log(`
▶ Message ${item.id}${slot.key === '' ? '' : ` (session ${slot.key})`}: ${item.text}`)
    let note = ''
    let pendingCaseId = null
    let activeCaseId = null
    let activeCaseIds = []
    let actualCaseId = null
    try {
      const seg = await runCaseTurn(slot, item.text, {
        policy: 'return',
        caseType: item.caseType,
        caseTypePinnedForTurn: item.caseTypePinned === true || caseTypePinned,
        businessKey: item.businessKey,
        requestedCaseId: item.caseId,
      })
      note = seg.note
      pendingCaseId = seg.pendingCaseId
      activeCaseId = seg.activeCaseId
      activeCaseIds = seg.activeCaseIds
      actualCaseId = seg.caseId
    } catch (e) {
      const credentialRejected = e instanceof AgentCredentialRejectedError
      const connectionReplaced = e instanceof McpConnectionReplacedError
      note = credentialRejected
        ? `Agent credential rejected: ${e.message}`
        : connectionReplaced
          ? `Agent connection replaced by a newer authenticated client: ${e.message}`
          : `Task aborted with an unexpected error: ${e?.message ?? e}`
      actualCaseId = board.roots[0]?.caseId ?? null
      activeCaseId = actualCaseId
      activeCaseIds = board.roots.map((row) => row.caseId)
      pendingCaseId = actualCaseId
      if (credentialRejected || connectionReplaced) {
        // A revoked credential and a replaced connection both belong to the whole host
        // rather than to one task: neither is retryable per task, and continuing to admit
        // work would queue segments that can never be carried. Stop admission, let every
        // running slot record its real outcome, and leave the reconnect decision to a person.
        acceptingTasks = false
        process.exitCode = credentialRejected ? 3 : 4
        terminalizeQueuedTasks(note)
      }
      log(`✗ ${note}`)
    } finally {
      // Bookkeeping lives in `finally`: nothing above may pin this slot as busy forever.
      // That client could never be served again, and the symptom — "202 on submit, no
      // result ever" — has no log line that explains it.
      if (inFlight === flight) inFlight = undefined
      slot.busy = false
      slot.taskId = undefined
      slot.lastUsed = Date.now()
    }
    const rec = {
      id: item.id, text: item.text, at: item.at,
      startedAt: flight.startedAt, endedAt: Date.now(), note,
      board: agentId,
      ...(actualCaseId === null ? {} : { caseId: actualCaseId }),
      ...(activeCaseId === null ? {} : { activeCaseId }),
      ...(activeCaseIds.length === 0 ? {} : { activeCaseIds }),
      ...(slot.key === '' ? {} : { sessionKey: slot.key }),
      // pendingCaseId is reserved for a detached/paused Case. A healthy Case selected by
      // this conversation is activeCaseId; callers must not escalate ordinary dialogue.
      ...(pendingCaseId === null ? {} : { pendingCaseId }),
      ...(actualCaseId === null ? {} : { console: consoleUrl }),
    }
    pushRun(rec)
    emit('task-done', rec)
    log(`· ${note}${activeCaseId === null ? '' : ` · Active Rulith Case: ${activeCaseId}.`}${pendingLine(pendingCaseId)}${actualCaseId === null ? '' : ` · Verify in Console: ${consoleUrl}`}
`)
    if (!acceptingTasks && inFlight === undefined) {
      for (const client of clients) client.end()
      serveSrv.close()
      serveSrv.closeAllConnections()
      // Nothing further will be sent for this Agent, so the session goes back rather than
      // being left for the Gateway to expire.
      await endSession()
    }
  }
  // The scheduler: sweep the slots and start every idle slot that has work, up to the
  // cross-slot ceiling. A segment is async and is deliberately not awaited here —
  // awaiting one would pin concurrency back to 1. Each finished segment pumps again, so
  // "start the next one as soon as a place frees" needs no timer.
  function pump() {
    if (!acceptingTasks) return
    for (const slot of allSlots()) {
      if (inFlight !== undefined) return
      if (slot.busy || slot.queue.length === 0) continue
      // The `.catch` is not decoration: an unhandled rejection ends a Node process, and
      // in an unattended deployment that takes the whole service down over one task.
      // `runOne` already wraps the work; this layer covers what surrounds it.
      void runOne(slot)
        .catch((e) => log(`✗ Scheduler error; the queue will continue: ${e?.message ?? e}`))
        .finally(pump)
    }
  }
  // A task on the command line means the first message is already in hand, so a script
  // can start the process, handle one message, and go on accepting more. It carries no
  // sessionKey, so it lands in the default slot.
  if (TASK !== '') { defaultSlot.queue.push({ id: nextTaskId(), text: TASK, caseType: selectedCaseType, businessKey: selectedBusinessKey, at: Date.now(), sessionKey: '' }); pump() }
} else if (!CHAT) {
  // ── One-shot (CI/script form) ──
  try {
  log(`Task: ${TASK}
`)
  emit('start', { agentId, url: URL_BASE, task: TASK })
  const { note, outcome, caseId, activeCaseIds, pendingCaseId, opened } = await runCaseTurn(defaultSlot, TASK, { policy: 'continue' })
  // The run's own verdict, on the terminal. It used to travel only in the `end` event, so
  // the one interface this form actually has never said how the run ended.
  log(`\n· ${note}`)
  const seen = consoleUrl
  log('\n──────── Board View last observed ────────')
  log(board.lastView === undefined ? '(No Board View was observed; inspect the Case records in Console.)' : viewText(board.lastView))
  if (pendingCaseId !== null) log(`⚠ This case remains open: pending_case_id=${pendingCaseId}. Resume with --case ${pendingCaseId}, or resolve it in Console.`)
  log(`
Verify the task tree, work items, and conclusions in Console: ${seen}
`)
  emit('end', {
    // The success bit is read from the loop's own outcome, not from the prose it printed.
    // A note is for a person; a caller that greps it is one rewording away from silence.
    ok: outcome === 'completed',
    outcome,
    note,
    caseId,
    ...(activeCaseIds.length === 0 ? {} : { activeCaseIds }),
    board: agentId,
    console: seen,
    ...(pendingCaseId === null ? {} : { pendingCaseId }),
  })
  // A task that never opened a Case did not run. Exiting 0 told every caller — CI step,
  // shell script, cron wrapper — that the work was attempted and finished.
  //
  // The status is set rather than forced. `process.exit()` here tore the loop down
  // while pipe writes and the HTTP client's sockets were still closing, and on Windows
  // libuv aborts on that (`!(handle->flags & UV_HANDLE_CLOSING)`, src/win/async.c):
  // roughly half of successful runs on this platform reported 3221226505 — a crash
  // code — instead of 0, and the tail of stdout was lost with it.
  if (opened !== true) {
    console.error(`\n✗ No Case Context was opened, so this task never started: ${note}`
      + '\n   Nothing was executed and no Case record exists. Fix the reported cause and run the task again.\n')
    process.exitCode = 1
  } else {
    process.exitCode = 0
  }
  await endSession()
  } catch (error) {
    if (error instanceof McpConnectionReplacedError) {
      console.error(`\n✗ ${error.message}`
        + '\n   The task stopped here. Whatever was already dispatched keeps its identity at the authority and is not'
        + ' cancelled by the replacement; check it in Console before running the task again.\n')
      process.exitCode = 4
    } else {
      if (!(error instanceof AgentCredentialRejectedError)) throw error
      console.error(`\n✗ ${error.message}\n`)
      process.exitCode = 3
    }
  }
} else {
  // Interactive terminal client. Browser interaction belongs to the Rulith Local host.
  const inbox = []
  let wake = null
  let stdinOpen = true
  const pushInput = (text) => {
    const t = String(text ?? '').trim()
    if (t === '') return
    inbox.push(t)
    if (wake) { const w = wake; wake = null; w() }
  }
  const nextInput = async () => {
    for (;;) {
      if (inbox.length > 0) return inbox.shift()
      // stdin closed (the pipe is drained) and no other face is feeding it: finish
      // honestly rather than throwing (ERR_USE_AFTER_CLOSE was seen on a real machine).
      if (!stdinOpen) return null
      await new Promise((r) => { wake = r })
    }
  }
  const { createInterface } = await import('node:readline')
  const rl = createInterface({ input: process.stdin })
  rl.on('line', (l) => pushInput(l))
  rl.on('close', () => { stdinOpen = false; if (wake) { const w = wake; wake = null; w() } })
  // An interjection does not interrupt: something said while a segment is running joins
  // that round. It comes from the same inbox, so the terminal, a pipe and the browser all
  // get the capability without separate wiring.
  //
  // The watermark is the whole trick: lines already queued when a segment starts are the
  // *next* segments, not interjections. Without it, `printf '1\n2\nexit\n'` had "2"
  // swallowed as an interjection to "1". The criterion is arrival time — only what
  // arrives after the segment started counts.
  let queuedAtSegmentStart = 0
  pollInterject = () => (inbox.length > queuedAtSegmentStart ? inbox.splice(queuedAtSegmentStart, 1)[0] : undefined)

  log(`Interactive mode. This is a normal Agent conversation; Rulith is an optional tool. Cases are created only when the Agent chooses governed work. Verify any resulting Cases and conclusions in Console: ${consoleUrl}`)
  log('The transcript stays on this machine and is not written to the board. Empty lines are ignored. Use exit, quit, or Ctrl+C to stop.\n')
  emit('start', { agentId, url: URL_BASE, task: '(interactive)' })
  for (;;) {
    if (inbox.length === 0 && stdinOpen) process.stdout.write('You> ')
    const line = await nextInput()
    if (line === null) break
    if (line === 'exit' || line === 'quit') break
    emit('user', { text: line })
    queuedAtSegmentStart = inbox.length
    let segment
    try {
      segment = await runCaseTurn(defaultSlot, line, { policy: 'return' })
    } catch (error) {
      if (error instanceof McpConnectionReplacedError) {
        console.error(`\n✗ ${error.message}`
          + '\n   This conversation cannot continue: another authenticated client is now this Agent\'s effective client.'
          + ' Nothing was cancelled at the authority. Start this Runtime again to take the connection back deliberately.\n')
        process.exitCode = 4
        break
      }
      if (!(error instanceof AgentCredentialRejectedError)) throw error
      console.error(`\n✗ ${error.message}\n`)
      process.exitCode = 3
      break
    }
    const { note, caseId, activeCaseId, activeCaseIds, pendingCaseId } = segment
    emit('segment-end', { note, board: agentId, caseId,
      ...(activeCaseId === null ? {} : { activeCaseId }),
      ...(activeCaseIds.length === 0 ? {} : { activeCaseIds }),
      ...(pendingCaseId === null ? {} : { pendingCaseId }) })
    log(`
· ${note}${activeCaseId === null ? '' : ` · Active Rulith Case: ${activeCaseId}.`}${pendingLine(pendingCaseId)}${caseId === null ? '' : ` · Verify in Console: ${consoleUrl}`}
`)
  }
  rl.close()
  await endSession()
  log('Stopped.')
  if (process.exitCode === undefined) process.exitCode = 0
}
