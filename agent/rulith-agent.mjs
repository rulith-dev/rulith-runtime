const userEntry = (text) => ({ role: 'user', text: String(text) })
const hostRecoveryEntry = (text) => ({ role: 'host_recovery', text: String(text) })
const assistantEntry = (text, toolCalls = [], reasoningContent) => ({ role: 'assistant', text: String(text ?? ''), toolCalls,
  ...(typeof reasoningContent === 'string' ? { reasoningContent } : {}) })
const resultsEntry = (results) => ({ role: 'tool_results', results })

/** Shorten only repeated, identical successful QueryBoard snapshots in a request.
 * A newer focused or partial view does not supersede earlier observations of another
 * scope. Keep command receipts, refusals, Artifact data and the stored transcript intact. */
function requestEntries(entries) {
  const beforeBytes = Buffer.byteLength(JSON.stringify(entries))
  if (beforeBytes < 32 * 1024) return { entries, compactedViews: 0, compactedTranscriptBytes: 0 }
  const views = [], latest = new Map()
  for (let index = 0; index < entries.length; index++) {
    if (entries[index].role !== 'tool_results' || !Array.isArray(entries[index].results)) continue
    for (let resultIndex = 0; resultIndex < entries[index].results.length; resultIndex++) {
      const result = entries[index].results[resultIndex]
      if (result.name !== 'QueryBoard') continue
      let parsed
      try { parsed = JSON.parse(result.text) } catch { continue }
      const field = parsed?.view?.cases ? 'view' : parsed?.payload?.cases ? 'payload' : ''
      if (parsed?.accepted === true && field !== '' && typeof parsed[field] === 'object' && !viewIsTruncated(parsed[field])) {
        const identity = field + ':' + JSON.stringify(parsed[field])
        const observation = { index, resultIndex, parsed, field, identity, id: result.id }
        views.push(observation)
        latest.set(identity, observation)
      }
    }
  }
  if (views.length < 2) return { entries, compactedViews: 0, compactedTranscriptBytes: 0 }
  const rewritten = entries.slice()
  let compactedViews = 0
  for (const observation of views) {
    const { index, resultIndex, parsed, field, identity } = observation
    const retained = latest.get(identity)
    if (retained === observation) continue
    if (rewritten[index] === entries[index]) rewritten[index] = { ...entries[index], results: entries[index].results.slice() }
    const rest = { ...parsed }
    delete rest[field]
    rewritten[index].results[resultIndex] = {
      ...entries[index].results[resultIndex],
      text: JSON.stringify({ ...rest, earlierBoardView: { identicalToToolCall: retained.id,
        note: 'The identical QueryBoard snapshot is retained at that later result in this request.' } }),
    }
    compactedViews += 1
  }
  return { entries: rewritten, compactedViews,
    compactedTranscriptBytes: beforeBytes - Buffer.byteLength(JSON.stringify(rewritten)) }
}

function renderMessages(entries, style) {
  const out = []
  for (const entry of entries) {
    if (entry.role === 'host_recovery') {
      out.push(style === 'anthropic'
        ? { role: 'assistant', content: [{ type: 'text', text: entry.text }] }
        : { role: 'assistant', content: entry.text })
      continue
    }
    if (entry.role === 'user') {
      out.push(style === 'anthropic' ? { role: 'user', content: [{ type: 'text', text: entry.text }] } : { role: 'user', content: entry.text })
      continue
    }
    if (entry.role === 'assistant') {
      const calls = Array.isArray(entry.toolCalls) ? entry.toolCalls : []
      if (style === 'anthropic') {
        const content = []
        if (entry.text !== '') content.push({ type: 'text', text: entry.text })
        for (const call of calls) content.push({ type: 'tool_use', id: call.id, name: call.name, input: call.input ?? {} })
        out.push({ role: 'assistant', content: content.length > 0 ? content : [{ type: 'text', text: '(no content)' }] })
        continue
      }
      if (style === 'openai') {
        out.push({
          role: 'assistant',
          // `null` content is only legal beside tool_calls. A turn with neither is a
          // model that answered nothing, and the endpoint refuses the whole request.
          content: entry.text !== '' ? entry.text : calls.length === 0 ? '(no content)' : null,
          // Provider continuation metadata stays in the local transcript; never publish it as prose or Board evidence.
          ...(typeof entry.reasoningContent === 'string' ? { reasoning_content: entry.reasoningContent } : {}),
          ...(calls.length === 0 ? {} : { tool_calls: calls.map((call) => ({ id: call.id, type: 'function', function: { name: call.name, arguments: JSON.stringify(call.input ?? {}) } })) }),
        })
        continue
      }
      const spoken = calls.map((call) => JSON.stringify({ tool: call.name, input: call.input ?? {} })).join('\n')
      out.push({ role: 'assistant', content: [entry.text, spoken].filter((part) => part !== '').join('\n') || '(no content)' })
      continue
    }
    const results = Array.isArray(entry.results) ? entry.results : []
    if (style === 'anthropic') {
      out.push({ role: 'user', content: results.map((result) => ({ type: 'tool_result', tool_use_id: result.id, content: result.text })) })
      continue
    }
    if (style === 'openai') {
      for (const result of results) out.push({ role: 'tool', tool_call_id: result.id, content: result.text })
      continue
    }
    out.push({ role: 'user', content: results.map((result) => `[${result.name} result]\n${result.text}`).join('\n\n') })
  }
  return out
}

/**
 * Fold adjacent same-role messages into one.
 *
 * The Anthropic wire expects alternating turns, and the loop legitimately produces two
 * user messages in a row — the tool results, then the host's own nudge. Merging here
 * means the loop never has to think about it, and no future caller can reintroduce the
 * malformed shape by pushing one more message.
 */
function mergeAdjacent(messages) {
  const out = []
  for (const message of messages) {
    const previous = out[out.length - 1]
    if (previous === undefined || previous.role !== message.role || previous.tool_calls !== undefined) { out.push(message); continue }
    if (Array.isArray(previous.content) && Array.isArray(message.content)) previous.content = [...previous.content, ...message.content]
    else if (typeof previous.content === 'string' && typeof message.content === 'string') previous.content = `${previous.content}\n\n${message.content}`
    else out.push(message)
  }
  return out
}

/** The emulated transport's only addition: the same schemas, described instead of sent. */
const emulatedToolGuide = (tools) => [
  'This model endpoint cannot receive tool definitions, so the same tools are described here.',
  'To call one, reply with exactly one JSON object and nothing else: {"tool":"<name>","input":{...}}',
  'To answer instead, reply with ordinary text and no JSON object.',
  '',
  ...tools.map((tool) => `${tool.name}: ${tool.description}\ninput schema: ${JSON.stringify(tool.schema)}`),
].join('\n')

/**
 * The first number literal in a JSON text that the exact number domain cannot hold, or
 * undefined. The Board holds integers within ±(2^53 − 1) and finite numbers only
 * (exact-or-fail), and a literal beyond that has already lost precision by the time
 * `JSON.parse` returns — 9007199254740993 comes back as 9007199254740992 — so the look
 * happens on the text, before parsing. Strings are skipped: a number inside a string is
 * text, and writing a large identifier as a string is exactly what the teaching asks for.
 */
export function inexactNumberLiteral(text) {
  const s = String(text ?? '')
  const number = /-?\d+(\.\d+)?([eE][+-]?\d+)?/y
  let i = 0
  while (i < s.length) {
    const c = s[i]
    if (c === '"') {
      i += 1
      while (i < s.length && s[i] !== '"') i += s[i] === '\\' ? 2 : 1
      i += 1
      continue
    }
    if (c === '-' || (c >= '0' && c <= '9')) {
      number.lastIndex = i
      const m = number.exec(s)
      if (m === null) { i += 1; continue }
      const literal = m[0]
      i += literal.length
      if (m[1] === undefined && m[2] === undefined) {
        const digits = literal.startsWith('-') ? literal.slice(1) : literal
        if (digits.length >= 16 && BigInt(digits) > 9007199254740991n) return literal
      } else {
        const value = Number(literal)
        if (!Number.isFinite(value) || (Number.isInteger(value) && Math.abs(value) > 9007199254740991)) return literal
        // Underflow is the same disease in the other direction: `1e-400` parses to 0, a
        // value the model never wrote. A mantissa with a non-zero digit that lands on zero
        // is refused too.
        if (value === 0 && /[1-9]/.test(literal.split(/[eE]/)[0])) return literal
      }
      continue
    }
    i += 1
  }
  return undefined
}

/** One JSON object is one call; anything else is an ordinary answer. */
function parseEmulated(text) {
  const trimmed = String(text ?? '').trim()
  const fenced = /^```(?:json)?\s*([\s\S]*?)```$/.exec(trimmed)
  const candidate = fenced === null ? trimmed : fenced[1].trim()
  if (!candidate.startsWith('{')) return { text: trimmed, toolCalls: [] }
  let value
  try { value = JSON.parse(candidate) } catch { return { text: trimmed, toolCalls: [] } }
  if (value === null || typeof value !== 'object' || Array.isArray(value) || typeof value.tool !== 'string') {
    return { text: trimmed, toolCalls: [] }
  }
  const input = value.input !== null && typeof value.input === 'object' && !Array.isArray(value.input) ? value.input : {}
  const inexact = inexactNumberLiteral(candidate)
  return { text: '', toolCalls: [{ id: `emulated_${++emulatedSeq}`, name: value.tool, input, ...(inexact === undefined ? {} : { inexact }) }] }
}

/** Tool arguments that are not a JSON object are refused locally rather than guessed at. */
function parseToolArguments(raw) {
  if (raw === undefined || raw === null) return {}
  if (typeof raw === 'object' && !Array.isArray(raw)) return raw
  // Several OpenAI-compatible endpoints send `""` for a tool with no arguments. That is
  // an empty object, not a malformed call; refusing it would refuse every no-arg verb.
  if (typeof raw === 'string' && raw.trim() === '') return {}
  try {
    const value = JSON.parse(String(raw))
    return value !== null && typeof value === 'object' && !Array.isArray(value) ? value : undefined
  } catch { return undefined }
}

/**
 * One model turn.
 *
 * Returns `{ text, toolCalls }`: prose the user should see, and the calls the model
 * decided to make. Which of the three transports carried it is not visible above this
 * line, and must not be — the loop reasons about tool calls, never about wire shapes.
 */
/** Model formatters need concrete field shapes instead of local refs and simple allOf
 * intersections. Expand only local, non-recursive refs and merge compatible constraints.
 * Keep alternatives and any intersection that cannot be merged without changing meaning.
 * The MCP contract and the arguments sent back to it are never modified. */
function openAIParameters(schema) {
  const definitions = schema?.$defs ?? {}
  const annotations = new Set(['description', 'title', '$comment', 'default', 'examples', '$schema', '$defs'])
  const equal = (a, b) => JSON.stringify(a) === JSON.stringify(b)
  function intersect(left, right) {
    if (!left || !right || typeof left !== 'object' || typeof right !== 'object') return undefined
    // Combining closed property tables can otherwise admit fields one branch forbids.
    for (const [closed, other] of [[left, right], [right, left]]) {
      if (closed.additionalProperties === false && other.properties
        && Object.keys(other.properties).some(key => !Object.hasOwn(closed.properties ?? {}, key))) return undefined
    }
    const out = { ...left }
    for (const [key, value] of Object.entries(right)) {
      if (!Object.hasOwn(out, key)) Object.defineProperty(out, key, { value, enumerable: true, writable: true, configurable: true })
      else if (equal(out[key], value) || annotations.has(key)) continue
      else if (key === 'required') out[key] = [...new Set([...out[key], ...value])]
      else if (key === 'items') { const merged = intersect(out[key], value); if (!merged) return undefined; out[key] = merged }
      else if (key === 'properties') {
        const fields = { ...out[key] }
        for (const [name, shape] of Object.entries(value)) {
          const merged = Object.hasOwn(fields, name) ? intersect(fields[name], shape) : shape
          if (merged === undefined) return undefined
          Object.defineProperty(fields, name, { value: merged, enumerable: true, writable: true, configurable: true })
        }
        out[key] = fields
      } else return undefined
    }
    return out
  }
  function expose(node, seen = new Set()) {
    if (!node || typeof node !== 'object' || Array.isArray(node)) return node
    let out = { ...node }
    if (typeof node.$ref === 'string' && node.$ref.startsWith('#/$defs/') && !seen.has(node.$ref)
      && Object.keys(node).every(key => key === '$ref' || annotations.has(key))) {
      const key = node.$ref.slice('#/$defs/'.length)
      const target = Object.hasOwn(definitions, key) ? definitions[key] : undefined
      if (target) {
        seen = new Set([...seen, node.$ref])
        const expanded = expose(target, seen)
        if (!Object.hasOwn(expanded, '$ref')) { out = { ...expanded, ...out }; delete out.$ref }
      }
    }
    if (out.properties) out.properties = Object.fromEntries(Object.entries(out.properties).map(([key, value]) => [key, expose(value, seen)]))
    if (out.items) out.items = expose(out.items, seen)
    for (const key of ['allOf', 'oneOf', 'anyOf']) if (Array.isArray(out[key])) out[key] = out[key].map(value => expose(value, seen))
    if (Array.isArray(out.allOf)) {
      const { allOf, ...base } = out
      let merged = base
      for (const part of allOf) { merged = intersect(merged, part); if (!merged) break }
      if (merged) out = merged
    }
    const alternatives = out.oneOf ?? out.anyOf ?? []
    if (out.type === undefined && Object.hasOwn(out, 'const')) out.type = out.const === null ? 'null' : Array.isArray(out.const) ? 'array' : typeof out.const
    if (out.type === undefined && alternatives[0]?.type && alternatives.every(part => equal(part.type, alternatives[0].type))) out.type = alternatives[0].type
    if (out.type === 'object' && out.properties === undefined && alternatives.length
      && alternatives.every(part => part.type === 'object' && part.properties && part.additionalProperties === false)) {
      const fields = new Map()
      for (const part of alternatives) for (const [name, value] of Object.entries(part.properties)) {
        const choices = fields.get(name) ?? []
        if (!choices.some(prior => equal(prior, value))) choices.push(value)
        fields.set(name, choices)
      }
      out.properties = Object.fromEntries([...fields].map(([name, choices]) => [name, expose(choices.length === 1 ? choices[0] : { anyOf: choices }, seen)]))
    }
    if (out.enum === undefined && out.anyOf?.length && out.anyOf.every(part => Object.hasOwn(part, 'const') && (part.const === null || ['string', 'number', 'boolean'].includes(typeof part.const)) && Object.keys(part).every(key => ['const', 'type'].includes(key)) && (part.type === undefined || part.type === (part.const === null ? 'null' : typeof part.const)))) {
      out.enum = [...new Set(out.anyOf.map(part => part.const))]; delete out.anyOf
    }
    return out
  }
  return expose(schema)
}

async function ask(entries, system, { tools = [], cfg = MAIN_CFG, onUsage } = {}) {
  const started = performance.now()
  const wire = openaiStyle(cfg) ? 'openai' : 'anthropic'
  // The optional shadow has its own endpoint/model; do not copy main-provider settings to it.
  const thinking = cfg === MAIN_CFG ? process.env.RULITH_MODEL_THINKING : undefined
  const style = emulatedTools ? 'emulated' : wire
  const declared = !emulatedTools && tools.length > 0
  const systemText = emulatedTools && tools.length > 0 ? `${system}\n\n${emulatedToolGuide(tools)}` : system
  const baseHeaders = { 'content-type': 'application/json' }
  const headers = wire === 'openai'
    ? (cfg.key === '' ? baseHeaders : { ...baseHeaders, authorization: `Bearer ${cfg.key}` })
    : (cfg.key === '' ? baseHeaders : { ...baseHeaders, 'x-api-key': cfg.key, 'anthropic-version': '2023-06-01' })
  const { entries: suppliedEntries, compactedViews, compactedTranscriptBytes } = requestEntries(entries)
  const body = wire === 'openai'
    ? {
        model: cfg.model, max_tokens: cfg.maxOutputTokens,
        // Omission uses the provider default. An explicit disable must reach providers that default to thinking.
        ...(['enabled', 'disabled'].includes(thinking) ? { thinking: { type: thinking } } : {}),
        messages: [{ role: 'system', content: systemText }, ...renderMessages(suppliedEntries, style)],
        ...(declared ? { tools: tools.map((tool) => ({ type: 'function', function: { name: tool.name, description: tool.description, parameters: openAIParameters(tool.schema) } })) } : {}),
      }
    : {
        model: cfg.model, max_tokens: cfg.maxOutputTokens, system: systemText, messages: mergeAdjacent(renderMessages(suppliedEntries, style)),
        ...(declared ? { tools: tools.map((tool) => ({ name: tool.name, description: tool.description, input_schema: tool.schema })) } : {}),
      }
  // Report sizes, never prompt text. Provider token counts alone say how expensive a
  // call was; these three numbers show whether history, fixed instructions or tool
  // declarations made it grow during a long document-authoring turn.
  const requestBody = JSON.stringify(body)
  const requestSize = {
    requestBytes: Buffer.byteLength(requestBody),
    transcriptBytes: Buffer.byteLength(JSON.stringify(body.messages)),
    messageCount: entries.length,
    compactedViews,
    compactedTranscriptBytes,
  }
  let response
  try {
    response = await fetch(cfg.url, { method: 'POST', headers, body: requestBody })
  } catch (error) {
    // A user-facing tool does not print a raw stack: say who was called and how to change it.
    onUsage?.({ durationMs: Math.round(performance.now() - started), inputTokens: null, outputTokens: null,
      cachedInputTokens: null, uncachedInputTokens: null, httpStatus: null, ...requestSize })
    failTask(`Cannot reach model service ${cfg.url}: ${error?.cause?.code ?? error?.message ?? error}.
   Set RULITH_MODEL_URL for a self-hosted or proxy endpoint. Leave it unset when using the default provider endpoint.`)
    return { text: '', toolCalls: [] }
  }
  const raw = await response.text().catch(() => '')
  let payload
  try { payload = JSON.parse(raw) } catch { payload = {} }
  const tokenCount = n => Number.isSafeInteger(n) && n >= 0 ? n : null
  const inputTokens = tokenCount(wire === 'openai' ? payload.usage?.prompt_tokens : payload.usage?.input_tokens)
  const cacheHit = wire === 'openai' ? tokenCount(payload.usage?.prompt_cache_hit_tokens) : null
  const cacheMiss = wire === 'openai' ? tokenCount(payload.usage?.prompt_cache_miss_tokens) : null
  const cacheBreakdownValid = inputTokens !== null && cacheHit !== null && cacheMiss !== null
    && cacheHit + cacheMiss === inputTokens
  onUsage?.({ durationMs: Math.round(performance.now() - started), httpStatus: response.status, ...requestSize,
    inputTokens, cachedInputTokens: cacheBreakdownValid ? cacheHit : null,
    uncachedInputTokens: cacheBreakdownValid ? cacheMiss : null,
    outputTokens: tokenCount(wire === 'openai' ? payload.usage?.completion_tokens : payload.usage?.output_tokens) })
  if (!response.ok) {
    if (response.status === 400 && declared && /(?:does not support|unsupported|unrecognized|unknown)\s+(?:the\s+)?tools?\b|\btools?\b.{0,60}(?:not supported|unsupported)/i.test(raw)) {
      // The endpoint refuses tool definitions. Describe the identical schemas in the
      // prompt instead of dropping the tools: a model with no tools is not a fallback,
      // it is an agent that can no longer reach the Board.
      emulatedTools = true
      log('The model endpoint refused a request carrying tool definitions. The same seven tools are now described in the prompt; their names and schemas are unchanged.')
      return await ask(entries, system, { tools, cfg, onUsage })
    }
    failTask(`Model service error (${response.status}): ${raw.replace(/\s+/g, ' ').slice(0, 300)}`)
    return { text: '', toolCalls: [] }
  }
  // A truncated or empty provider response is not a delivered answer. In particular,
  // reasoning can exhaust the output budget before any text or tool call is produced.
  // Refuse the entire truncated turn so even a syntactically valid partial call cannot run.
  const finishReason = wire === 'openai' ? payload?.choices?.[0]?.finish_reason : payload?.stop_reason
  if (finishReason === 'length' || finishReason === 'max_tokens') {
    return { text: '', toolCalls: [], failure: 'The model reached its output token limit before finishing this response. No tools from this response were executed. Increase the output token limit in model settings if the provider supports it, then continue the same conversation.' }
  }
  const spokenText = wire === 'openai'
    ? payload?.choices?.[0]?.message?.content
    : (Array.isArray(payload?.content) ? payload.content : []).filter(block => block?.type === 'text').map(block => String(block.text ?? '')).join('\n')
  const nativeCalls = wire === 'openai'
    ? payload?.choices?.[0]?.message?.tool_calls
    : (Array.isArray(payload?.content) ? payload.content : []).filter(block => block?.type === 'tool_use')
  if (!(typeof spokenText === 'string' && spokenText.trim()) && (emulatedTools || !Array.isArray(nativeCalls) || nativeCalls.length === 0)) {
    return { text: '', toolCalls: [], failure: 'The model returned no answer or tool call. No tools from this response were executed. Continue the same conversation to try again, or check the model settings.' }
  }
  if (emulatedTools) {
    const spoken = wire === 'openai'
      ? String(payload.choices?.[0]?.message?.content ?? '')
      : (Array.isArray(payload.content) ? payload.content : []).filter((block) => block?.type === 'text').map((block) => String(block.text ?? '')).join('\n')
    return parseEmulated(spoken)
  }
  if (wire === 'openai') {
    const message = payload.choices?.[0]?.message ?? {}
    return {
      text: String(message.content ?? ''),
      ...(typeof message.reasoning_content === 'string' ? { reasoningContent: message.reasoning_content } : {}),
      toolCalls: (Array.isArray(message.tool_calls) ? message.tool_calls : []).map((call, index) => {
        // Chat Completions carries the arguments as JSON *text*, so the exactness look
        // is on that text; a literal beyond the exact domain is refused before parsing.
        const inexact = typeof call.function?.arguments === 'string' ? inexactNumberLiteral(call.function.arguments) : undefined
        return {
          id: String(call.id ?? `call_${index}`),
          name: String(call.function?.name ?? ''),
          input: parseToolArguments(call.function?.arguments),
          ...(inexact === undefined ? {} : { inexact }),
        }
      }),
    }
  }
  // Messages carries `input` as parsed JSON inside the response, so the only place a
  // literal beyond the exact domain is still visible is the response text itself. Provider
  // metadata carries small integers only; a hit is attributed to the calls of this turn.
  const inexact = inexactNumberLiteral(raw)
  const blocks = Array.isArray(payload.content) ? payload.content : []
  return {
    text: blocks.filter((block) => block?.type === 'text').map((block) => String(block.text ?? '')).join('\n'),
    toolCalls: blocks.filter((block) => block?.type === 'tool_use').map((block, index) => ({
      id: String(block.id ?? `call_${index}`),
      name: String(block.name ?? ''),
      input: parseToolArguments(block.input),
      ...(inexact === undefined ? {} : { inexact }),
    })),
  }
}

