/**
 * Project the vendored Worker protocol into the Worker's single source file.
 *
 * `worker/rulith-worker.mjs` ships the way the Agent does: one file, downloaded on its own,
 * hashed on its own, run from wherever it lands. So the contract is compiled in between two
 * markers rather than read from a sibling at startup, and `--check` fails when the compiled
 * copy has drifted from the bundle. Generation is one-directional: the bundle is the
 * source, the block is a build product, and nothing reads the block back.
 *
 *   node scripts/generate-worker-protocol.mjs           # write the projection
 *   node scripts/generate-worker-protocol.mjs --check   # fail if it has drifted
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

import { loadWorkerContract } from './verify-worker-contract.mjs'

const ROOT = resolve(import.meta.dirname, '..')
const WORKER = resolve(ROOT, 'worker', 'rulith-worker.mjs')
export const BEGIN = '// ── BEGIN GENERATED WORKER PROTOCOL PROJECTION ──────────────────────────────'
export const END = '// ── END GENERATED WORKER PROTOCOL PROJECTION ────────────────────────────────'

export function workerProjectionBlock(contract) {
  const list = (values) => values.map((value) => `'${value}'`).join(', ')
  return `${BEGIN}
//
// Generated by scripts/generate-worker-protocol.mjs from protocol/worker-contract.json.
// Do not edit: \`npm run check\` regenerates this block and fails on any difference. Every
// value below is the contract's, read from the bundle exported at the commit named here.
const RULITH_WORKER_CONTRACT_SOURCE_COMMIT = '${contract.sourceCommit}'
/** The one serialization rule the two execution vectors share, and nothing else uses. */
const EXECUTION_CANONICALIZATION = '${contract.canonicalizationRule}'
const EXECUTION_REQUEST_VERSION = '${contract.requestVersion}'
const EXECUTION_RESULT_VERSION = '${contract.resultVersion}'
/** Fresh per process, never a configured deployment label: the pattern says so. */
const WORKER_ID_PATTERN = ${new RegExp(contract.workerIdPattern).toString()}
/** The only two protected upstream headers for Worker identity. */
const WORKER_HEADER_ID = '${contract.headerNames.workerId}'
const WORKER_HEADER_GENERATION = '${contract.headerNames.workerGeneration}'
/** Case identity left the Worker hop entirely; naming one is a refusal, not a fallback. */
const RETIRED_HOP_FIELDS = Object.freeze([${list(contract.retiredHopFields)}])
const SHADOW_ACTION_FIELDS = Object.freeze([${list(contract.actionWorkShadowFields)}])
const WORK_TYPES = Object.freeze([${list(contract.workTypes)}])
/** The whole Worker inbox verb. The Core operation ListWork is not a Worker API. */
const POLL_KIND = '${contract.pollKind}'
const MAX_ADVERTISED_TOOLS = ${contract.maxAdvertisedTools}
//
// The advertised Tool descriptor, as the contract states it. These were hand-written
// membership tests until this projection existed, and a hand-written copy of an enum is a
// second source of truth that goes stale in silence — the local copy refuses what the
// contract allows and nothing anywhere says which one is right.
/** The seven accredited Source types. An empty list is a Source-free Tool, not an omission. */
const SOURCE_TYPES = Object.freeze([${list(contract.sourceTypes)}])
const TOOL_ID_PATTERN = ${new RegExp(contract.toolIdPattern).toString()}
/** Bare lowercase sha256, deliberately unprefixed: this is the Tool pin, not a byte digest. */
const TOOL_DIGEST_PATTERN = ${new RegExp(contract.toolDigestPattern).toString()}
const TOOL_KINDS = Object.freeze([${list(contract.toolKinds)}])
/** Both forms, plain and optional; a trailing question mark marks an optional slot. */
const PARAM_TYPE_TOKENS = Object.freeze([${list(contract.paramTypes)}])
const PARAM_NAME_PATTERN = ${new RegExp(contract.paramNamePattern).toString()}
const RETURN_PREDICATE = ${new RegExp(contract.returnPredicatePattern).toString()}
const MAX_RETURN_ROWS = ${contract.maxReturnRows}
//
// The execution grant, field by field, read off the contract's own shape. A field added
// upstream lands here as a drift failure rather than as a field nothing compares against.
// 'text' is a non-empty string, 'text?' one the contract lets be empty.
const EXECUTION_GRANT_SHAPE = Object.freeze({
${Object.entries(contract.grantShape).map(([name, kind]) => `  ${name}: '${kind}',`).join('\n')}
})
const EXECUTION_GRANT_CONST = Object.freeze(${JSON.stringify(contract.grantConst)})
const DIGEST_PATTERN = ${new RegExp(contract.digestPattern).toString()}
const GENERATION_MAXIMUM = ${contract.generationMaximum}
//
// The dispatched action row, the same way. Closed: the contract requires every field it
// declares and admits no other, so a row is checked for all of them and for nothing else.
// 'toolPin' is the bare lowercase Tool digest the Connection lock holds.
const ACTION_ROW_SHAPE = Object.freeze({
${Object.entries(contract.actionRowShape).map(([name, kind]) => `  ${name}: '${kind}',`).join('\n')}
})
const ACTION_ROW_CONST = Object.freeze(${JSON.stringify(contract.actionRowConst)})
${END}`
}

export function withWorkerProjection(source, block) {
  const from = source.indexOf(BEGIN)
  const to = source.indexOf(END)
  if (from < 0 || to < 0 || to < from) {
    throw new Error('worker/rulith-worker.mjs no longer carries the generated protocol markers.'
      + ' The projection has nowhere to go; restore the BEGIN/END pair around the generated block.')
  }
  return `${source.slice(0, from)}${block}${source.slice(to + END.length)}`
}

if (process.argv[1]?.endsWith('generate-worker-protocol.mjs')) {
  const contract = loadWorkerContract(ROOT)
  const source = readFileSync(WORKER, 'utf8')
  const updated = withWorkerProjection(source, workerProjectionBlock(contract))
  if (process.argv.includes('--check')) {
    if (updated !== source) {
      console.error('✗ worker/rulith-worker.mjs has drifted from protocol/worker-contract.json.'
        + '\n  Regenerate with: node scripts/generate-worker-protocol.mjs')
      process.exitCode = 1
    } else {
      console.log(`worker protocol projection: worker/rulith-worker.mjs matches ${contract.sourceCommit}`)
    }
  } else {
    writeFileSync(WORKER, updated)
    console.log(`worker protocol projection: wrote the ${contract.sourceCommit} hop into worker/rulith-worker.mjs`)
  }
}
