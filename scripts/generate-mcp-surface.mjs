/**
 * Project the verified contract bundle into the Agent's single source file.
 *
 * `agent/rulith-agent.mjs` ships as one file: it is downloaded on its own, hashed on its
 * own in `artifact-manifest.json`, and run from wherever it lands. Reading the bundle at
 * startup would mean shipping a second file beside it and inventing a rule for finding it —
 * a new loading protocol for every deployment, including the ones that already fetched the
 * agent by URL. So the contract is compiled **in**: this generator writes the projection
 * between two markers, and `--check` fails when what is in the file is not what the bundle
 * says. Generation is one-directional. The bundle is the source; the inline block is a
 * build product; nothing ever reads the block back into the bundle.
 *
 *   node scripts/generate-mcp-surface.mjs           # write the projection
 *   node scripts/generate-mcp-surface.mjs --check   # fail if it has drifted
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

import { loadContractBundle } from './verify-mcp-contract.mjs'

const ROOT = resolve(import.meta.dirname, '..')
const AGENT = resolve(ROOT, 'agent', 'rulith-agent.mjs')
export const BEGIN = '// ── BEGIN GENERATED CONTRACT PROJECTION ─────────────────────────────────────'
export const END = '// ── END GENERATED CONTRACT PROJECTION ───────────────────────────────────────'

/** The block, exactly as it must appear in the Agent. */
export function projectionBlock(bundle) {
  const tools = bundle.tools.map((tool) => `  Object.freeze({ name: '${tool.name}', target: '${tool.target}'`
    + `${tool.operation === undefined ? '' : `, operation: '${tool.operation}'`}`
    + `${tool.resultSchemaRef === undefined ? '' : `, resultSchemaRef: '${tool.resultSchemaRef}'`} }),`).join('\n')
  const capabilities = Object.entries(bundle.clientCapabilities)
    .map(([name, value]) => `${name}: ${JSON.stringify(value)}`).join(', ')
  const states = bundle.recoveryStates.map((state) => `'${state}'`).join(', ')
  return `${BEGIN}
//
// Generated by scripts/generate-mcp-surface.mjs from protocol/mcp-contract.json. Do not
// edit: \`npm run check\` regenerates this block and fails on any difference. Every value
// below is the contract's, read from the bundle exported at the commit named here.
//
// \`target\` is why the list is not just names. The Core tools dispatch to Board operations
// and their results carry a Board View; the artifact read is the Gateway's private result
// data plane and returns bytes. Treating an artifact read as a Board answer would let a
// data read update focus and lifecycle, which is exactly the confusion the targets prevent.
const RULITH_CONTRACT_SOURCE_COMMIT = '${bundle.sourceCommit}'
const MCP_PROTOCOL_VERSION = '${bundle.protocolVersion}'
/** The reserved key for host metadata. It never appears in model content or tool schemas. */
const RULITH_META = '${bundle.metadataNamespace}'
/**
 * What this host declares at initialize: the compatibility statement the contract's
 * \`ClientCapabilities\` defines, and nothing more. It is not a grant of authority — a
 * Gateway that does not see it must refuse this host before any business executes.
 */
const HOST_CAPABILITIES = Object.freeze({ ${capabilities} })
/** The recovery states the contract defines. Anything else is unreadable, never "none". */
const RECOVERY_STATES = new Set([${states}])
const RULITH_MCP_SURFACE = Object.freeze([
${tools}
])
${END}`
}

/** Replace the block in the Agent source, or say that the markers are gone. */
export function withProjection(source, block) {
  const from = source.indexOf(BEGIN)
  const to = source.indexOf(END)
  if (from < 0 || to < 0 || to < from) {
    throw new Error('agent/rulith-agent.mjs no longer carries the generated contract markers.'
      + ' The projection has nowhere to go; restore the BEGIN/END pair around the generated block.')
  }
  return `${source.slice(0, from)}${block}${source.slice(to + END.length)}`
}

if (process.argv[1]?.endsWith('generate-mcp-surface.mjs')) {
  const bundle = loadContractBundle(ROOT)
  const source = readFileSync(AGENT, 'utf8')
  const updated = withProjection(source, projectionBlock(bundle))
  if (process.argv.includes('--check')) {
    if (updated !== source) {
      console.error('✗ agent/rulith-agent.mjs has drifted from protocol/mcp-contract.json.'
        + '\n  The tool surface, protocol version, metadata namespace, client capabilities and recovery states'
        + ' are the contract\'s to declare. Regenerate with: node scripts/generate-mcp-surface.mjs')
      process.exitCode = 1
    } else {
      console.log(`contract projection: agent/rulith-agent.mjs matches ${bundle.sourceCommit}`)
    }
  } else {
    writeFileSync(AGENT, updated)
    console.log(`contract projection: wrote ${bundle.tools.length} tool(s) from ${bundle.sourceCommit} into agent/rulith-agent.mjs`)
  }
}
